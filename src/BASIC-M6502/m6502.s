;SEE WHAT RELATION HOLDS.
    ldy ARGHO
    cpy FACHO
;[C]=0,1. N(C=0)=0.
    bne SAVQUO
.if (ADDPRC) <> 0
    ldy ARGMOH
    cpy FACMOH
    bne SAVQUO
.endif
    ldy ARGMO
    cpy FACMO
    bne SAVQUO
    ldy ARGLO
    cpy FACLO
SAVQUO:
