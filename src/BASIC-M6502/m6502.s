    tax
    ldy #.lobyte(0)
;MOVE ONE AHEAD.
    inx
STRPR2:
    dex
;ALL DONE.
    beq PRTRTS
;PNTR TO ACT STRNG SET BY FREFAC.
    lda (INDEX),y
    jsr OUTDO
    iny
    cmp #.lobyte(13)
    bne STRPR2
;TYPE REST OF CARRIAGE RETURN.
    jsr CRFIN
;AND ON AND ON.
    jmp STRPR2
;
; OUTDO OUTPUTS THE CHARACTER IN ACCA, USING CNTWFL
; (SUPPRESS OR NOT), TRMPOS (PRINT HEAD POSITION),
; TIMING, ETCQ. NO REGISTERS ARE CHANGED.
;
OUTSPC:
.if (REALIO-3) <> 0
    lda #.lobyte(32)
.endif
.if (REALIO-3) = 0
    lda CHANNL
    beq CRTSKP
    lda #.lobyte(32)
    SKIP2
;COMMODORE'S SKIP CHARACTER.
CRTSKP:
    lda #.lobyte(29)
.endif
    SKIP2
OUTQST:
    lda #.lobyte(63)
OUTDO:
.if (REALIO) <> 0
;SHOULDN'T AFFECT CHANNEL I/O!
    bit CNTWFL
    bmi OUTRTS
.endif
.if (REALIO-3) <> 0
    pha
;IS THIS A PRINTING CHAR?
    cmp #.lobyte(32)
;NO, DON'T INCLUDE IT IN TRMPOS.
    bcc TRYOUT
    lda TRMPOS
;LENGTH = TERMINAL WIDTH?
    cmp LINWID
    bne OUTDO1
;YES, TYPE CRLF
    jsr CRDO
OUTDO1:
.if (EXTIO) <> 0
    lda CHANNL
    bne TRYOUT
.endif
;INCREMENT COUNT.
INCTRM:
    inc TRMPOS
;RESTORE THE A REGISTER
TRYOUT:
    pla
.endif

.if (REALIO-1) = 0
;PRESERVE Y.
    sty KIMY
.endif
;TURN ON B7 FOR APPLE.
.if (REALIO-4) = 0
    ora #.lobyte(128)
.endif
.if (REALIO) <> 0
;OUTPUT THE CHARACTER.
OUTLOC:
    jsr OUTCH
.endif
.if (REALIO-1) = 0
;GET Y BACK.
    ldy KIMY
.endif
.if (REALIO-2) = 0
.repeat 4
    nop
.endrepeat
.endif
;GET [A] BACK FROM APPLE.
.if (REALIO-4) = 0
    and #.lobyte(127)
.endif

.if (REALIO) = 0
;CALL SIMULATOR OUTPUT ROUTINE
    .error "PDP-10 simulator instruction is not supported"
.endif
;SET Z=0.
OUTRTS:
    and #.lobyte(255)
GETRTS:
    rts

; INPUT AND READ CODE.
;
; HERE WHEN THE DATA THAT WAS TYPED IN OR IN "DATA" STATEMENTS
; IS IMPROPERLY FORMATTED. FOR "INPUT" WE START AGAIN.
; FOR "READ" WE GIVE A SYNTAX ERROR AT THE DATA LINE.
;
TRMNOK:
    lda INPFLG
;IF INPUT TRY AGAIN.
    beq TRMNO1
.if (GETCMD) <> 0
    bmi GETDTL
;MAKE IT LOOK DIRECT.
    ldy #.lobyte(255)
;ALWAYS GOES.
    BNEA STCURL
GETDTL:
.endif
;GET DATA LINE NUMBER.
    LDWD DATLIN
;MAKE IT CURRENT LINE.
STCURL:
    STWD CURLIN
SNERR4:
    jmp SNERR
TRMNO1:
.if (EXTIO) <> 0
;IF NOT TERMINAL, GIVE BAD DATA.
    lda CHANNL
    beq DOAGIN
    ldx #.lobyte(ERRBD)
    jmp ERROR
.endif
DOAGIN:
    LDWDI TRYAGN
;PRINT "?REDO FROM START".
    jsr STROUT
;POINT AT START
    LDWD OLDTXT
;OF THIS CURRENT LINE.
    STWD TXTPTR
;GO TO "NEWSTT".
    rts
.if (GETCMD) <> 0
;DIRECT IS NOT OK.
GET:
    jsr ERRDIR
.if (EXTIO) <> 0
;SEE IF "GET#".
    cmp #.lobyte(35)
;NO, JUST GET TTY INPUT.
    bne GETTTY
;MOVE UP TO NEXT BYTE.
    jsr CHRGET
;GET CHANNEL INTO X
    jsr GETBYT
;COMMA?
    SYNCHK 44
;GET CHANNEL OPEN FOR INPUT.
    jsr CQOIN
    stx CHANNL
.endif
;POINT TO 0.
GETTTY:
    LDXYI BUF+1
.if (BUFPAG) <> 0
;TO STUFF AND TO POINT.
    lda #.lobyte(0)
    sta BUF+1
.endif
.if (BUFPAG) = 0
;ZERO IT.
    sty BUF+1
.endif
;TURN ON V-BIT.
    lda #.lobyte(64)
;DO THE GET.
    jsr INPCO1
.if (EXTIO) <> 0
    ldx CHANNL
;RELEASE.
    bne IORELE
.endif
    rts
.endif

.if (EXTIO) <> 0
;GET CHANNEL NUMBER.
INPUTN:
    jsr GETBYT
;A COMMA?
    SYNCHK 44
;GO WHERE COMMODORE CHECKS IN OPEN.
    jsr CQOIN
    stx CHANNL
;DO INPUT TO VARIABLES.
    jsr NOTQTI
;RELEASE CHANNEL.
IODONE:
    lda CHANNL
IORELE:
    jsr CQCCHN
;RESET CHANNEL TO TERMINAL.
    ldx #.lobyte(0)
    stx CHANNL
    rts
.endif
INPUT:
.if (REALIO) <> 0
;BE TALKATIVE.
    lsr CNTWFL
.endif
;A QUOTE?
    cmp #.lobyte(34)
;NO MESSAGE.
    bne NOTQTI
;LITERALIZE THE STRING IN TEXT
    jsr STRTXT
;MUST END WITH SEMICOLON.
    SYNCHK 59
;PRINT IT OUT.
    jsr STRPRT
;USE COMMON ROUTINE SINCE DEF DIRECT
NOTQTI:
    jsr ERRDIR
;GET COMMA.
    lda #.lobyte(44)
    sta BUF-1
;IS ALSO ILLEGAL.
;TYPE "?" AND INPUT A LINE OF TEXT.
GETAGN:
    jsr QINLIN
.if (EXTIO) <> 0
    lda CHANNL
    beq BUFFUL
;GET STATUS BYTE.
    lda CQSTAT
    and #.lobyte(2)
;A-OK.
    beq BUFFUL
;BAD. CLOSE CHANNEL.
    jsr IODONE
;SKIP REST OF INPUT.
    jmp DATA
BUFFUL:
.endif
;ANYTHING INPUT?
    lda BUF
;YES, CONTINUE.
    bne INPCON
.if (EXTIO) <> 0
;BLANK LINE MEANS GET ANOTHER.
    lda CHANNL
;IF NOT TERMINAL.
    bne GETAGN
.endif
;MAKE SURE DONT PRINT BREAK
    clc
;NO, STOP.
    jmp STPEND
QINLIN:
.if (EXTIO) <> 0
    lda CHANNL
    bne GINLIN
.endif
    jsr OUTQST
    jsr OUTSPC
GINLIN:
    jmp INLIN
;GET LAST DATA LOCATION.
READ:
    LDXY DATPTR
;LDAI TYA TO MAKE IT NONZERO.
    .byte 169
.if (BUFPAG) = 0
INPCON:
.endif
    tya
.if (BUFPAG) <> 0
    SKIP2
;SET FLAG THAT THIS IS INPUT
INPCON:
    lda #.lobyte(0)
.endif
;STORE THE FLAG.
INPCO1:
    sta INPFLG
;
; IN THE PROCESSING OF DATA AND READ STATEMENTS:
; ONE POINTER POINTS TO THE DATA (IE, THE NUMBERS BEING FETCHED)
; AND ANOTHER POINTS TO THE LIST OF VARIABLES.
;
; THE POINTER INTO THE DATA ALWAYS STARTS POINTING TO A
; TERMINATOR -- A , : OR END-OF-LINE.
;
; AT THIS POINT TXTPTR POINTS TO LIST OF VARIABLES AND
; [Y,X] POINTS TO DATA OR INPUT LINE.
;
    STXY INPPTR
;READ VARIABLE LIST.
INLOOP:
    jsr PTRGET
;SAVE POINTER FOR "LET" STRING STUFFING.
    STWD FORPNT
;RETURNS PNTR TOP VAR IN VARPNT.
;SAVE TEXT PNTR.
    LDWD TXTPTR
    STWD VARTXT
    LDXY INPPTR
    STXY TXTPTR
;GET IT AND SET Z IF TERM.
    jsr CHRGOT
    bne DATBK1
    bit INPFLG
.if (GETCMD) <> 0
    bvc QDATA
;DON'T WANT INCHR. JUST ONE.
    jsr CZGETL
.if (REALIO-4) = 0
    and #.lobyte(127)
.endif
;MAKE IT FIRST CHARACTER.
    sta BUF
;POINT JUST BEFORE IT.
    LDXYI (BUF-1)
.if (BUFPAG) = 0
    BEQA DATBK
.endif
.if (BUFPAG) <> 0
;GO PROCESS.
    BNEA DATBK
.endif
.endif
;SEARCH FOR ANOTHER DATA STATEMENT.
QDATA:
    bmi DATLOP
.if (EXTIO) <> 0
    lda CHANNL
    bne GETNTH
.endif
    jsr OUTQST
;GET ANOTHER LINE.
GETNTH:
    jsr QINLIN
;SET FOR "CHRGET".
DATBK:
    STXY TXTPTR
DATBK1:
    jsr CHRGET
;GET VALUE TYPE.
    bit VALTYP
;INPUT A NUMBER IF NUMERIC.
    bpl NUMINS
.if (GETCMD) <> 0
;GET?
    bit INPFLG
;NO, GO SET QUOTE.
    bvc SETQUT
    inx
    stx TXTPTR
;ZERO TERMINATORS.
    lda #.lobyte(0)
    sta CHARAC
    BEQA RESETC
.endif
;ASSUME QUOTED STRING.
SETQUT:
    sta CHARAC
;TERMINATORS OK?
    cmp #.lobyte(34)
;YES.
    beq NOWGET
;SET TERMINATORS TO ":" AND
    lda #.lobyte(58)
    sta CHARAC
;COMMA.
    lda #.lobyte(44)
RESETC:
    clc
NOWGET:
    sta ENDCHR
    LDWD TXTPTR
;C IS SET PROPERLY ABOVE.
    adc #.lobyte(0)
    bcc NOWGE1
    iny
;MAKE A STRING DESCRIPTOR FOR THE VALUE
NOWGE1:
    jsr STRLT2
;AND COPY IF NECESSARY.
;SET TEXT POINTER.
    jsr ST2TXT
;DO ASSIGNMENT.
    jsr INPCOM
    jmp STRDN2
NUMINS:
    jsr FIN
.if (INTPRC) = 0
    jsr MOVVF
.endif
.if (INTPRC) <> 0
;SET CODES ON FLAG.
    lda INTFLG
;GO DECIDE ON FLOAT.
    jsr QINTGR
.endif
;READ LAST CHARACTER.
STRDN2:
    jsr CHRGOT
;":" OR EOL IS OK.
    beq TRMOK
;A COMMA?
    cmp #.lobyte(44)
    JNE TRMNOK
TRMOK:
    LDWD TXTPTR
;SAVE FOR MORE READS.
    STWD INPPTR
    LDWD VARTXT
;POINT TO VARIABLE LIST.
    STWD TXTPTR
;LOOK AT LAST VARIABLE LIST CHARACTER.
    jsr CHRGOT
;THAT'S THE END OF THE LIST.
    beq VAREND
;NOT END. CHECK FOR COMMA.
    jsr CHKCOM
    jmp INLOOP
;
; SUBROUTINE TO FIND DATA
; THE SEARCH IS MADE BY USING THE EXECUTION CODE FOR DATA TO
; SKIP OVER STATEMENTS. THE START WORD OF EACH STATEMENT
; IS COMPARED WITH "DATATK". EACH NEW LINE NUMBER
; IS STORED IN "DATLIN" SO THAT IF AN ERROR OCCURS
; WHILE READING DATA THE ERROR MESSAGE CAN GIVE THE LINE
; NUMBER OF THE ILL-FORMATTED DATA.
;
;SKIP SOME TEXT.
DATLOP:
    jsr DATAN
    iny
;END OF LINE?
    tax
;SHO AIN'T.
    bne NOWLIN
;YES = "NO DATA" ERROR.
    ldx #.lobyte(ERROD)
    iny
    lda (TXTPTR),y
    beq ERRGO5
    iny
;GET HIGH BYTE OF LINE NUMBER.
    lda (TXTPTR),y
    sta DATLIN
    iny
;GET LOW BYTE.
    lda (TXTPTR),y
    iny
    sta DATLIN+1
;HOW IS IT?
NOWLIN:
    lda (TXTPTR),y
    tax
;ADD [Y] TO [TXTPTR].
    jsr ADDON
;IS IT A "DATA" STATEMENT.
    cpx #.lobyte(DATATK)
;NOT QUITE RIGHT. KEEP LOOKING.
    bne DATLOP
;THIS IS THE ONE !
    jmp DATBK1
;PUT AWAY A NEW DATA PNTR MAYBE.
VAREND:
    LDWD INPPTR
    ldx INPFLG
    bpl VARY0
    jmp RESFIN
VARY0:
    ldy #.lobyte(0)
;LAST DATA CHR COULD HAVE BEEN
    lda (INPPTR),y
;COMMA OR COLON BUT SHOULD BE NULL.
;IT IS NULL.
    beq INPRTS
.if (EXTIO) <> 0
;IF NOT TERMINAL, NO TYPE.
    lda CHANNL
    bne INPRTS
.endif
    LDWDI EXIGNT
;TYPE "?EXTRA IGNORED"
    jmp STROUT
;DO NEXT STATEMENT.
INPRTS:
    rts
EXIGNT:
    DT "?EXTRA IGNORED"
    ACRLF
    .byte 0
TRYAGN:
    DT "?REDO FROM START"
    ACRLF
    .byte 0
; THE NEXT CODE IS THE "NEXT CODE"
;
; A "FOR" ENTRY ON THE STACK HAS THE FOLLOWING FORMAT:
;
; LOW ADDRESS
;	TOKEN (FORTK) 1 BYTE
;	A POINTER TO THE LOOP VARIABLE 2 BYTES
;	THE STEP 4+ADDPRC BYTES
;	A BYTE REFLECTING THE SIGN OF THE INCREMENT 1 BYTE
;	THE UPPER VALUE (PACKED) 4+ADDPRC BYTES
;	THE LINE NUMBER OF THE "FOR" STATEMENT 2 BYTES
;	A TEXT POINTER INTO THE "FOR" STATEMENT 2 BYTES
; HIGH ADDRESS
;
; TOTAL 16+2*ADDPRC BYTES.
;
NEXT:
    bne GETFOR
;WITHOUT ARG CALL "FNDFOR" WITH
    ldy #.lobyte(0)
;[FORPNT]=0.
    BEQA STXFOR
;GET A POINTER TO LOOP VARIABLE
GETFOR:
    jsr PTRGET
;INTO "FORPNT".
STXFOR:
    STWD FORPNT
;FIND THE MATCHING ENTRY IF ANY.
    jsr FNDFOR
    beq HAVFOR
;"NEXT WITHOUT FOR".
    ldx #.lobyte(ERRNF)
ERRGO5:
    beq ERRGO4
;SETUP STACK. CHOP FIRST.
HAVFOR:
    txs
    txa
    clc
;POINT TO INCREMENT
    adc #.lobyte(4)
;SAVE THIS POINTER TO RESTORE TO [A]
    pha
;POINT TO UPPER LIMIT
    adc #.lobyte(5+ADDPRC)
;SAVE AS INDEX
    sta INDEX2
;RESTORE POINTER TO INCREMENT
    pla
;SET HI ADDR OF THING TO MOVE.
    ldy #.lobyte(1)
;GET QUANTITY INTO THE FAC.
    jsr MOVFM
    tsx
;SET SIGN CORRECTLY.
    lda 257+7+ADDPRC,X
    sta FACSGN
    LDWD FORPNT
;ADD INC TO LOOP VARIABLE.
    jsr FADD
;PACK THE FAC INTO MEMORY.
    jsr MOVVF
    ldy #.lobyte(1)
;COMPARE FAC WITH UPPER VALUE.
    jsr FCOMPN
    tsx
    sec
;SUBTRACT SIGN OF INC FROM SIGN OF
    sbc 257+7+ADDPRC,X
;OF (CURRENT VALUE-FINAL VALUE).
;IF SIGN (FINAL-CURRENT)-SIGN STEP=0
    beq LOOPDN
;THEN LOOP IS DONE.
    lda 2*ADDPRC+12+257,X
;STORE LINE NUMBER OF "FOR" STATEMENT.
    sta CURLIN
    lda 257+13+(2*ADDPRC),X
    sta CURLIN+1
    lda 2*ADDPRC+15+257,X
;STORE TEXT PNTR INTO "FOR" STATEMENT.
    sta TXTPTR
    lda 2*ADDPRC+14+257,X
    sta TXTPTR+1
;PROCESS NEXT STATEMENT.
NEWSGO:
    jmp NEWSTT
LOOPDN:
    txa
;ADDS 16 WITH CARRY.
    adc #.lobyte(2*ADDPRC+15)
    tax
;NEW STACK PNTR.
    txs
    jsr CHRGOT
;COMMA AT END?
    cmp #.lobyte(44)
    bne NEWSGO
    jsr CHRGET
;DO NEXT BUT DON'T ALLOW BLANK VARIABLE
    jsr GETFOR
;PNTR. [VARPNT] IS THE STK PNTR WHICH
;NEVER MATCHES ANY POINTER.
;JSR TO PUT ON DUMMY NEWSTT ADDR.

; FORMULA EVALUATION CODE.
;
; THESE ROUTINES CHECK FOR CERTAIN "VALTYP".
; [C] IS NOT PRESERVED.
;
FRMNUM:
    jsr FRMEVL
CHKNUM:
    clc
    SKIP1
;SET CARRY.
CHKSTR:
    sec
;WILL NOT F UP "VALTYP".
CHKVAL:
    bit VALTYP
    bmi DOCSTR
    bcs CHKERR
CHKOK:
    rts
DOCSTR:
    bcs CHKOK
CHKERR:
    ldx #.lobyte(ERRTM)
ERRGO4:
    jmp ERROR
;
; THE FORMULA EVALUATOR STARTS WITH
; [TXTPTR] POINTING TO THE FIRST CHARACTER OF THE FORMULA.
; AT THE END [TXTPTR] POINTS TO THE TERMINATOR.
; THE RESULT IS LEFT IN THE FAC.
; ON RETURN [A] DOES NOT REFLECT THE TERMINATOR.
;
; THE FORMULA EVALUATOR USES THE OPERATOR LIST (OPTAB)
; TO DETERMINE PRECEDENCE AND DISPATCH ADDRESSES FOR 
; EACH OPERATOR.
; A TEMPORARY RESULT ON THE STACK HAS THE FOLLOWING FORMAT.
;	THE ADDRESS OF THE OPERATOR ROUTINE.
;	THE FLOATING POINT TEMPORARY RESULT.
;	THE PRECEDENCE OF THE OPERATOR.
;
FRMEVL:
    ldx TXTPTR
    bne FRMEV1
    dec TXTPTR+1
FRMEV1:
    dec TXTPTR
;INITIAL DUMMY PRECEDENCE IS 0.
    ldx #.lobyte(0)
    SKIP1
;SAVE LOW PRECEDENCE. (MASK.)
LPOPER:
    pha
    txa
;SAVE HIGH PRECEDENCE.
    pha
    lda #.lobyte(1)
;MAKE SURE THERE IS ROOM FOR
    jsr GETSTK
;RECURSIVE CALLS.
;EVALUATE SOMETHING.
    jsr EVAL
;PREPARE TO BUILD MASK MAYBE.
    CLR OPMASK
;REGET LAST CHARACTER.
TSTOP:
    jsr CHRGOT
;PREP TO SUBTRACT.
LOPREL:
    sec
;IS CURRENT CHARACTER A RELATION?
    sbc #.lobyte(GREATK)
;NO. RELATIONS ALL THROUGH.
    bcc ENDREL
;REALLY RELATIONAL?
    cmp #.lobyte(LESSTK-GREATK+1)
;NO -- JUST BIG.
    bcs ENDREL
;RESET CARRY FOR ZERO ONLY.
    cmp #.lobyte(1)
;0 TO 1, 1 TO 2, 2 TO 4.
    rol A
    eor #.lobyte(1)
;BRING IN THE OLD BITS.
    eor OPMASK
;MAKE SURE THE NEW MASK IS BIGGER.
    cmp OPMASK
;SYNTAX ERROR. BECAUSE TWO OF THE SAME.
    bcc SNERR5
;SAVE MASK.
    sta OPMASK
    jsr CHRGET
;GET THE NEXT CANDIDATE.
    jmp LOPREL
;WERE THERE ANY?
ENDREL:
    ldx OPMASK
;YES, HANDLE AS SPECIAL OP.
    bne FINREL
;NOT AN OPERATOR.
    bcs QOP
    adc #.lobyte(GREATK-PLUSTK)
;NOT AN OPERATOR.
    bcc QOP
;[C]=1.
    adc VALTYP
;ONLY IF [A]=0 AND [VALTYP]=-1 (A STR).
    JEQ CAT
;GET BACK ORIGINAL [A].
    adc #.lobyte(255)
    sta INDEX1
;MULTIPLY BY 2.
    asl A
;BY THREE.
    adc INDEX1
;SET UP FOR LATER.
    tay
;GET PREVIOUS PRECEDENCE.
QPREC:
    pla
;IS OLD PRECEDENCE GREATER OR EQUAL?
    cmp OPTAB,Y
;YES, GO OPERATE.
    bcs QCHNUM
;CAN'T BE STRING HERE.
    jsr CHKNUM
;SAVE OLD PRECEDENCE.
DOPREC:
    pha
;SET A RETURN ADDRESS FOR OP.
NEGPRC:
    jsr DOPRE1
;PULL OFF PREVIOUS PRECEDENCE.
    pla
;GET POINTER TO OP.
    ldy OPPTR
;THAT'S A REAL OPERATOR.
    bpl QPREC1
;DONE ?
    tax
;DONE !
    beq QOPGO
    bne PULSTK
;GET VALUE TYPE INTO "C".
FINREL:
    lsr VALTYP
    txa
;PUT VALTYP INTO LOW ORDER BIT OF MASK.
    rol A
;DECREMENT TEXT POINTER.
    ldx TXTPTR
    bne FINRE2
    dec TXTPTR+1
FINRE2:
    dec TXTPTR
;MAKE [YREG] POINT AT OPERATOR ENTRY.
    ldy #.lobyte(PTDORL-OPTAB)
;SAVE THE OPERATION MASK.
    sta OPMASK
;SAVE IT ALL. BR ALWAYS.
    bne QPREC
;NOTE B7(VALTYP)=0 SO CHKNUM CALL IS OK.
;LAST PRECEDENCE IS GREATER?
QPREC1:
    cmp OPTAB,Y
;YES, GO OPERATE.
    bcs PULSTK
;NO SAVE ARGUMENT AND GET OTHER OPERAND.
    bcc DOPREC
DOPRE1:
    lda OPTAB+2,Y
;DISP ADDR GOES ONTO STACK.
    pha
    lda OPTAB+1,Y
    pha
;SAVE FAC ON STACK UNPACKED.
    jsr PUSHF1
;[ACCA] MAY BE MASK FOR REL.
    lda OPMASK
    jmp LPOPER
;GO TO AN ERROR.
SNERR5:
    jmp SNERR
PUSHF1:
    lda FACSGN
;GET HIGH PRECEDENCE.
    ldx OPTAB,Y
;GET POINTER INTO STACK.
PUSHF:
    tay
    pla
    sta INDEX1
    inc INDEX1
    pla
    sta INDEX1+1
    tya
;STORE FAC ON STACK UNPACKED.
;START WITH SIGN SET UP.
    pha
;PUT ROUNDED FAC ON STACK.
FORPSH:
    jsr ROUND
;ENTRY POINT TO SKIP STORING SIGN.
    lda FACLO
    pha
    lda FACMO
    pha
.if (ADDPRC) <> 0
    lda FACMOH
    pha
.endif
    lda FACHO
    pha
    lda FACEXP
    pha
;RETURN.
    jmp (INDEX1)
QOP:
    ldy #.lobyte(255)
;GET HIGH PRECEDENCE OF LAST OP.
    pla
;DONE !
QOPGO:
    beq QOPRTS
;RELATIONAL OPERATOR?
QCHNUM:
    cmp #.lobyte(100)
;YES, DON'T CHECK OPERAND.
    beq UNPSTK
;MUST BE NUMBER.
    jsr CHKNUM
;SAVE OPERATOR'S POINTER FOR NEXT TIME.
UNPSTK:
    sty OPPTR
;GET MASK FOR REL OP IF IT IS ONE.
PULSTK:
    pla
;SETUP [C] FOR DOREL'S "CHKVAL".
    lsr A
;SAVE FOR "DOCMP".
    sta DOMASK
;UNPACK STACK INTO ARG.
    pla
    sta ARGEXP
    pla
    sta ARGHO
.if (ADDPRC) <> 0
    pla
    sta ARGMOH
.endif
    pla
    sta ARGMO
    pla
    sta ARGLO
    pla
    sta ARGSGN
;GET PROBABLE RESULT SIGN.
    eor FACSGN
;ARITHMETIC SIGN. USED BY
    sta ARISGN
;ADD, SUB, MULT, DIV.
;GET IT AND SET CODES.
QOPRTS:
    lda FACEXP
;RETURN.
UNPRTS:
    rts

;ASSUME VALUE WILL BE NUMERIC.
EVAL:
    CLR VALTYP
;GET A CHARACTER.
EVAL0:
    jsr CHRGET
    bcs EVAL2
;IT IS A NUMBER.
EVAL1:
    jmp FIN
;VARIABLE NAME?
EVAL2:
    jsr ISLETC
;YES.
    bcs ISVAR
.if (REALIO-3) = 0
    cmp #.lobyte(PI)
    bne QDOT
    LDWDI PIVAL
;PUT VALUE IN FOR PI.
    jsr MOVFM
    jmp CHRGET
PIVAL:
    .byte 130
    .byte 73
    .byte 15
    .byte 218
    .byte 161
.endif
;LEADING CHARACTER OF CONSTANT?
QDOT:
    cmp #.lobyte(46)
    beq EVAL1
;NEGATION?
    cmp #.lobyte(MINUTK)
;SHO IS.
    beq DOMIN
    cmp #.lobyte(PLUSTK)
    beq EVAL0
;A QUOTE? A STRING?
    cmp #.lobyte(34)
    bne EVAL3
STRTXT:
    LDWD TXTPTR
;TO INC, ADD C=1.
    adc #.lobyte(0)
    bcc STRTX2
    iny
;YES. GO PROCESS IT.
STRTX2:
    jsr STRLIT
    jmp ST2TXT
;CHECK FOR "NOT" OPERATOR.
EVAL3:
    cmp #.lobyte(NOTTK)
    bne EVAL4
;"NOT" HAS PRECEDENCE 90.
    ldy #.lobyte(NOTTAB-OPTAB)
;GO DO ITS EVALUATION.
    bne GONPRC
;INTEGERIZE.
NOTOP:
    jsr AYINT
;GET THE ARGUMENT.
    lda FACLO
    eor #.lobyte(255)
    tay
    lda FACMO
    eor #.lobyte(255)
;FLOAT [Y,A] AS RESULT IN FAC.
    jmp GIVAYF
;AND RETURN.
;USER-DEFINED FUNCTION?
EVAL4:
    cmp #.lobyte(FNTK)
    JEQ FNDOER
;A FUNCTION NAME?
    cmp #.lobyte(ONEFUN)
;FUNCTIONS ARE THE HIGHEST NUMBERED
    bcc PARCHK
;CHARACTERS SO NO NEED TO CHECK
    jmp ISFUN
;AN UPPER-BOUND.
;ONLY POSSIBILITY LEFT IS
PARCHK:
    jsr CHKOPN
;A FORMULA IN PARENTHESIS.
    jsr FRMEVL
;RECURSIVELY EVALUATE THE FORMULA.
;CHECK FOR A RIGHT PARENTHESE
CHKCLS:
    lda #.lobyte(41)
    SKIP2
CHKOPN:
    lda #.lobyte(40)
    SKIP2
CHKCOM:
    lda #.lobyte(44)
;
; "SYNCHK" LOOKS AT THE CURRENT CHARACTER TO MAKE SURE IT
; IS THE SPECIFIC THING LOADED INTO ACCA JUST BEFORE THE CALL TO
; "SYNCHK". IF NOT, IT CALLS THE "SYNTAX ERROR" ROUTINE.
; OTHERWISE IT GOBBLES THE NEXT CHAR AND RETURNS,
;
; [A]=NEW CHAR AND TXTPTR IS ADVANCED BY "CHRGET".
;
SYNCHR:
    ldy #.lobyte(0)
;CHARACTERS EQUAL?
    cmp (TXTPTR),y
    bne SNERR
CHRGO5:
    jmp CHRGET
;"SYNTAX ERROR"
SNERR:
    ldx #.lobyte(ERRSN)
    jmp ERROR
;A PRECEDENCE BELOW "^".
DOMIN:
    ldy #.lobyte(NEGTAB-OPTAB)
;GET RID OF RTS ADDR.
GONPRC:
    pla
    pla
;EVALUTE FOR NEGATION.
    jmp NEGPRC

;GET A PNTR TO VARIABLE.
ISVAR:
    jsr PTRGET
ISVRET:
    STWD FACMO
.if (TIME|EXTIO) <> 0
;CHECK TIME,TIME$,STATUS.
    LDWD VARNAM
.endif
    ldx VALTYP
;THE STRING IS SET UP.
    beq GOOO
    ldx #.lobyte(0)
    stx FACOV
.if (TIME) <> 0
;AN ARRAY?
    bit FACLO
;YES.
    bpl STRRTS
;TI$?
    cmp #.lobyte(84)
    bne STRRTS
    cpy #.lobyte(73+128)
    bne STRRTS
;YES. PUT TIME IN FACMOH-LO.
    jsr GETTIM
;Y=0.
    sty TENEXP
    dey
    sty FBUFPT
;SIX	DIGITS TO PRINT.
    ldy #.lobyte(6)
    sty DECCNT
    ldy #.lobyte(FDCEND-FOUTBL)
;CONVERT TO ASCII.
    jsr FOUTIM
    jmp TIMSTR
.endif
STRRTS:
    rts
GOOO:
.if (INTPRC) <> 0
    ldx INTFLG
    bpl GOOOOO
    ldy #.lobyte(0)
;FETCH HIGH.
    lda (FACMO),y
    tax
    iny
    lda (FACMO),y
;PUT LOW IN Y.
    tay
;GET HIGH IN A.
    txa
;FLOAT AND RETURN.
    jmp GIVAYF
.endif
GOOOOO:
.if (TIME) <> 0
;AN ARRAY?
    bit FACLO
;YES.
    bpl GOMOVF
    cmp #.lobyte(84)
    bne QSTATV
    cpy #.lobyte(73)
    bne GOMOVF
    jsr GETTIM
;FOR FLOATB.
    tya
;SET EXPONNENT.
    ldx #.lobyte(160)
    jmp FLOATB
GETTIM:
    LDWDI (CQTIMR-2)
;TURN OF INT SYS.
    sei
    jsr MOVFM
;BACK ON.
    cli
;ZERO HIGHEST.
    sty FACHO
    rts
.endif
QSTATV:
.if (EXTIO) <> 0
    cmp #.lobyte(83)
    bne GOMOVF
    cpy #.lobyte(84)
    bne GOMOVF
    lda CQSTAT
    jmp FLOAT
GOMOVF:
.endif
.if (TIME|EXTIO) <> 0
    LDWD FACMO
.endif
;MOVE ACTUAL VALUE IN.
    jmp MOVFM
;AND RETURN.

;MULTIPLY BY TWO.
ISFUN:
    asl A
    pha
    tax
;SET UP FOR SYNCHK.
    jsr CHRGET
;IS IT PAST "LASNUM"?
    cpx #.lobyte(2*LASNUM-256+1)
;NO, MUST BE NORMAL FUNCTION.
    bcc OKNORM
;
; MOST FUNCTIONS TAKE A SINGLE ARGUMENT.
; THE RETURN ADDRESS OF THESE FUNCTIONS IS "CHKNUM"
; WHICH ASCERTAINS THAT [VALTYP]=0  (NUMERIC).
; NORMAL FUNCTIONS THAT RETURN STRING RESULTS
; (E.G., CHR$) MUST POP OFF THAT RETURN ADDR AND
; RETURN DIRECTLY TO "FRMEVL".
;
; THE SO-CALLED "FUNNY" FUNCTIONS CAN TAKE MORE THAN ONE ARGUMENT,
; THE FIRST OF WHICH MUST BE STRING AND THE SECOND OF WHICH
; MUST BE A NUMBER BETWEEN 0 AND 255.
; THE CLOSED PARENTHESIS MUST BE CHECKED AND RETURN IS DIRECTLY
; TO "FRMEVL" WITH THE TEXT PNTR POINTING BEYOND THE ")".
; THE POINTER TO THE DESCRIPTOR OF THE STRING ARGUMENT
; IS STORED ON THE STACK UNDERNEATH THE VALUE OF THE
; INTEGER ARGUMENT.
;
;CHECK FOR AN OPEN PARENTHESE
    jsr CHKOPN
;EAT OPEN PAREN AND FIRST ARG.
    jsr FRMEVL
;TWO ARGS SO COMMA MUST DELIMIT.
    jsr CHKCOM
;MAKE SURE FIRST WAS STRING.
    jsr CHKSTR
;GET FUNCTION NUMBER.
    pla
    tax
;SAVE POINTER AT STRING DESCRIPTOR
    PSHWD FACMO
    txa
;RESAVE FUNCTION NUMBER.
    pha
;THIS MUST BE ON STACK SINCE RECURSIVE.
;[X]=VALUE OF FORMULA.
    jsr GETBYT
;GET FUNCTION NUMBER.
    pla
    tay
    txa
    pha
;DISPATCH TO FUNCTION.
    jmp FINGO
;READ A FORMULA SURROUNDED BY PARENS.
OKNORM:
    jsr PARCHK
;GET DISPATCH FUNCTION.
    pla
    tay
;MODIFY DISPATCH ADDRESS.
FINGO:
    lda FUNDSP-2*ONEFUN+256,Y
    sta JMPER+1
    lda FUNDSP-2*ONEFUN+257,Y
    sta JMPER+2
;DISPATCH!
    jsr JMPER
;STRING FUNCTIONS REMOVE THIS RET ADDR.
;CHECK IT FOR NUMERICNESS AND RETURN.
    jmp CHKNUM

;MUST ALWAYS COMPLEMENT..
OROP:
    ldy #.lobyte(255)
    SKIP2
ANDOP:
    ldy #.lobyte(0)
;OPERATOR.
    sty COUNT
;[FACMO&LO]=INT VALUE AND CHECK SIZE.
    jsr AYINT
;USE DEMORGAN'S LAW ON HIGH
    lda FACMO
    eor COUNT
    sta INTEGR
;AND LOW.
    lda FACLO
    eor COUNT
    sta INTEGR+1
    jsr MOVFA
;[FACMO&LO]=INT OF ARG.
    jsr AYINT
    lda FACLO
    eor COUNT
    and INTEGR+1
;FINISH OUT DEMORGAN.
    eor COUNT
;SAVE HIGH.
    tay
    lda FACMO
    eor COUNT
    and INTEGR
    eor COUNT
;FLOAT [A.Y] AND RET TO USER.
    jmp GIVAYF

;
; TIME TO PERFORM A RELATIONAL OPERATOR.
; [DOMASK] CONTAINS THE BITS AS TO WHICH RELATIONAL
; OPERATOR IT WAS. CARRY BIT ON=STRING COMPARE.
;
;CHECK FOR MATCH.
DOREL:
    jsr CHKVAL
;IT IS A STRING.
    bcs STRCMP
;PACK ARG FOR FCOMP.
    lda ARGSGN
    ora #.lobyte(127)
    and ARGHO
    sta ARGHO
    LDWDI ARGEXP
    jsr FCOMP
    tax
    jmp QCOMP
;RESULT WILL BE NUMERIC.
STRCMP:
    CLR VALTYP
;TURN OFF VALTYP WHICH WAS STRING.
    dec OPMASK
;FREE THE FACLO STRING.
    jsr FREFAC
;SAVE FOR LATER.
    sta DSCTMP
    STXY DSCTMP+1
;GET POINTER TO OTHER STRING.
    LDWD ARGMO
;FREES FIRST DESC POINTER.
    jsr FRETMP
    STXY ARGMO
;COPY COUNT INTO X.
    tax
    sec
;WHICH IS GREATER. IF 0, ALL SET UP.
    sbc DSCTMP
;JUST PUT SIGN OF DIFFERENCE AWAY.
    beq STASGN
    lda #.lobyte(1)
;SIGN IS POSITIVE.
    bcc STASGN
;LENGTH OF FAC IS SHORTER.
    ldx DSCTMP
;GET A MINUS 1 FOR NEGATIVES.
    lda #.lobyte(255)
;KEEP FOR LATER.
STASGN:
    sta FACSGN
;SET POINTER TO FIRST STRING. (ARG.)
    ldy #.lobyte(255)
;TO LOOP PROPERLY.
    inx
NXTCMP:
    iny
;ANY CHARACTERS LEFT TO COMPARE?
    dex
;NOT DONE YET.
    bne GETCMP
;USE SIGN OF LENGTH DIFFERENCE
    ldx FACSGN
;SINCE ALL CHARACTERS ARE THE SAME.
;C IS ALWAYS SET THEN.
QCOMP:
    bmi DOCMP
    clc
;ALWAYS BRANCH.
    bcc DOCMP
;GET NEXT CHAR TO COMPARE.
GETCMP:
    lda (ARGMO),y
;SAME?
    cmp (DSCTMP+1),y
;YEP. TRY FURTHER.
    beq NXTCMP
;SET A POSITIVE DIFFERENCE.
    ldx #.lobyte(255)
;PUT STACK BACK TOGETHER.
    bcs DOCMP
;SET A NEGATIVE DIFFERENCE.
    ldx #.lobyte(1)
;-1 TO 1, 0 TO 2, 1 TO 4.
DOCMP:
    inx
    txa
    rol A
    and DOMASK
    beq GOFLOT
;MAP 0 TO 0. ALL OTHERS TO -1.
    lda #.lobyte(255)
;FLOAT THE ONE-BYTE RESULT INTO FAC.
GOFLOT:
    jmp FLOAT

; DIMENSION AND VARIABLE SEARCHING.
;
; THE "DIM" CODE SETS [DIMFLG] AND THEN FALLS INTO THE VARIABLE SEARCH
; ROUTINE, WHICH LOOKS AT DIMFLG AT THREE DIFFERENT POINTS.
;	1) IF AN ENTRY IS FOUND, "DIMFLG" BEING ON INDICATES
;		A "DOUBLY" DIMENSIONED VARIABLE.
;	2) WHEN A NEW ENTRY IS BEING BUILT "DIMFLG" BEING ON
;		INDICTAES THE INDICES SHOULD BE USED FOR THE
;		SIZE OF EACH INDEX. OTHERWISE THE DEFAULT OF TEN
;		IS USED.
;	3) WHEN THE BUILD ENTRY CODE FINISHES, ONLY IF "DIMFLG" IS OFF
;		WILL INDEXING BE DONE.
;
;MUST BE A COMMA
DIM3:
    jsr CHKCOM
;SET [ACCX] NONZERO.
DIM:
    tax
;[ACCA] MUST BE NONZERO TO WORK RIGHT.
DIM1:
    jsr PTRGT1
;GET LAST CHARACTER.
DIMCON:
    jsr CHRGOT
    bne DIM3
    rts
;
; ROUTINE TO READ THE VARIABLE NAME AT THE CURRENT TEXT POSITION
; AND  PUT A POINTER TO ITS VALUE IN VARPNT. [TXTPTR]
; POINTS TO THE TERMINATING CHARCTER.. NOT THAT EVALUATING SUBSCRIPTS
; IN A VARIABLE NAME CAN CAUSE RECURSIVE CALLS TO "PTRGET" SO AT
; THAT POINT ALL VALUES MUST BE STORED ON THE STACK.
;
;MAKE [ACCX]=0.
PTRGET:
    ldx #.lobyte(0)
;RETRIEVE LAST CHARACTER.
    jsr CHRGOT
;STORE FLAG AWAY.
PTRGT1:
    stx DIMFLG
PTRGT2:
    sta VARNAM
;GET CURRENT CHARACTER
    jsr CHRGOT
;MAYBE WITH FUNCTION BIT OFF.
;CHECK FOR LETTER.
    jsr ISLETC
;MUST HAVE A LETTER.
    bcs PTRGT3
INTERR:
    jmp SNERR
;ASSUME NO SECOND CHARACTER.
PTRGT3:
    ldx #.lobyte(0)
;DEFAULT IS NUMERIC.
    stx VALTYP
.if (INTPRC) <> 0
;ASSUME FLOATING.
    stx INTFLG
.endif
;GET FOLLOWING CHARACTER.
    jsr CHRGET
;CARRY RESET BY CHRGET IF NUMERIC.
    bcc ISSEC
;SET CARRY IF NOT ALPHABETIC.
    jsr ISLETC
;ALLOW ALPHABETICS.
    bcc NOSEC
;IT IS A NUMBER -- SAVE IN ACCX.
ISSEC:
    tax
;LOOK AT NEXT CHARACTER.
EATEM:
    jsr CHRGET
;SKIP NUMERICS.
    bcc EATEM
    jsr ISLETC
;SKIP ALPHABETICS.
    bcs EATEM
;IS IT A STRING?
NOSEC:
    cmp #.lobyte(36)
;IF NOT, [VALTYP]=0.
    bne NOTSTR
;SET [VALTYP]=255 (STRING !).
    lda #.lobyte(255)
    sta VALTYP
.if (INTPRC) <> 0
;ALWAYS GOES.
    BNEA TURNON
;INTEGER VARIABLE?
NOTSTR:
    cmp #.lobyte(37)
;NO.
    bne STRNAM
    lda SUBFLG
    bne INTERR
    lda #.lobyte(128)
;SET FLAG.
    sta INTFLG
;TURN ON BOTH HIGH BITS.
    ora VARNAM
    sta VARNAM
.endif
TURNON:
    txa
;TURN ON MSB OF SECOND CHARACTER.
    ora #.lobyte(128)
    tax
;GET CHARACTER AFTER $.
    jsr CHRGET
.if (INTPRC) = 0
NOTSTR:
.endif
;STORE AWAY SECOND CHARACTER.
STRNAM:
    stx VARNAM+1
    sec
;ADD FLAG WHETHER TO ALLOW ARRAYS.
    ora SUBFLG
;(CHECK FOR "(") WON'T MATCH IF SUBFLG SET. 
    sbc #.lobyte(40)
;IT IS!
    JEQ ISARY
;ALLOW SUBSCRIPTS AGAIN.
    CLR SUBFLG
;PLACE TO START SEARCH.
    lda VARTAB
    ldx VARTAB+1
    ldy #.lobyte(0)
STXFND:
    stx LOWTR+1
LOPFND:
    sta LOWTR
;AT END OF TABLE YET?
    cpx ARYTAB+1
    bne LOPFN
    cmp ARYTAB
;YES. WE COULDN'T FIND IT.
    beq NOTFNS
LOPFN:
    lda VARNAM
;COMPARE HIGH ORDERS.
    cmp (LOWTR),y
;NO COMPARISON.
    bne NOTIT
    lda VARNAM+1
    iny
;AND THE LOW PART?
    cmp (LOWTR),y
;THAT'S IT ! THAT'S IT !
    beq FINPTR
    dey
NOTIT:
    clc
    lda LOWTR
;MAKES NO DIF AMONG TYPES.
    adc #.lobyte(6+ADDPRC)
    bcc LOPFND
    inx
;ALWAYS BRANCHES.
    BNEA STXFND

;
; TEST FOR A LETTER.	/ CARRY OFF= NOT A LETTER.
;			  CARRY ON= A LETTER.
;
ISLETC:
    cmp #.lobyte(65)
;IF LESS THAN "A", RET.
    bcc ISLRTS
    sbc #.lobyte(90+1)
    sec
;RESET CARRY IF [A] .GT. "Z".
    sbc #.lobyte(256-90-1)
;RETURN TO CALLER.
ISLRTS:
    rts

;CHECK WHO'S CALLING.
NOTFNS:
    pla
;RESTORE IT.
    pha
;IS EVAL CALLING?
    cmp #.lobyte(ISVRET-1-(ISVRET-1)/256*256)
;NO, CARRY ON.
    bne NOTEVL
.if (REALIO-3) <> 0
    tsx
    lda 258,X
    cmp #.lobyte(((ISVRET-1)/256))
    bne NOTEVL
.endif
;SET UP PNTR TO SIMULATED ZERO.
LDZR:
    LDWDI ZERO
;FOR STRINGS OR NUMERIC.
    rts
;AND FOR INTEGERS TOO.
NOTEVL:
.if (TIME|EXTIO) <> 0
    LDWD VARNAM
.endif
.if (TIME) <> 0
    cmp #.lobyte(84)
    bne QSTAVR
    cpy #.lobyte(73+128)
    beq LDZR
    cpy #.lobyte(73)
    bne QSTAVR
.endif
.if (EXTIO|TIME) <> 0
GOBADV:
    jmp SNERR
.endif
QSTAVR:
.if (EXTIO) <> 0
    cmp #.lobyte(83)
    bne VAROK
    cpy #.lobyte(84)
    beq GOBADV
.endif
VAROK:
    LDWD ARYTAB
;LOWEST THING TO MOVE.
    STWD LOWTR
;GET HIGHEST ADDR TO MOVE.
    LDWD STREND
    STWD HIGHTR
    clc
    adc #.lobyte(6+ADDPRC)
    bcc NOTEVE
    iny
;PLACE TO STUFF IT.
NOTEVE:
    STWD HIGHDS
;MOVE IT ALL.
    jsr BLTU
;NOTE [Y,A] HAS [HIGHDS] FOR REASON.
;AND SET UP
    LDWD HIGHDS
    iny
;NEW START OF ARRAY TABLE.
    STWD ARYTAB
;GET ADDR OF VARIABLE ENTRY.
    ldy #.lobyte(0)
    lda VARNAM
    sta (LOWTR),y
    iny
    lda VARNAM+1
;STORE NAME OF VARIABLE.
    sta (LOWTR),y
    lda #.lobyte(0)
    iny
    sta (LOWTR),y
    iny
    sta (LOWTR),y
    iny
    sta (LOWTR),y
    iny
;FOURTH ZERO FOR DEF FUNC.
    sta (LOWTR),y
.if (ADDPRC) <> 0
    iny
    sta (LOWTR),y
.endif
FINPTR:
    lda LOWTR
    clc
    adc #.lobyte(2)
    ldy LOWTR+1
    bcc FINNOW
    iny
;THIS IS IT.
FINNOW:
    STWD VARPNT
    rts
; MULTIPLE DIMENSION CODE.
FMAPTR:
    lda COUNT
    asl A
;POINT TO ENTRIES. C CLR'D BY ASL.
    adc #.lobyte(5)
    adc LOWTR
    ldy LOWTR+1
    bcc JSRGM
    iny
JSRGM:
    STWD ARYPNT
    rts

;-32768.
N32768:
    .byte 144,128,0,0

;
; INTIDX READS A FORMULA FROM THE CURRENT POSITION AND
; TURNS IT INTO A POSITIVE INTEGER
; LEAVING THE RESULT IN FACMO&LO. NEGATIVE ARGUMENTS
; ARE NOT ALLOWED.
;
INTIDX:
    jsr CHRGET
;GET A NUMBER
    jsr FRMEVL
POSINT:
    jsr CHKNUM
    lda FACSGN
;IF NEGATIVE, BLOW HIM OUT.
    bmi NONONO
AYINT:
    lda FACEXP
;FAC .GT. 32767?
    cmp #.lobyte(144)
    bcc QINTGO
;GET ADDR OF -32768.
    LDWDI N32768
;SEE IF FAC=[[Y,A]].
    jsr FCOMP
;NO, FAC IS TOO BIG.
NONONO:
    bne FCERR
;GO TO QINT AND SHOVE IT.
QINTGO:
    jmp QINT
;
; FORMAT OF ARRAYS IN CORE.
;
; DESCRIPTOR:
;	LOWBYTE = FIRST CHARACTER.
;	HIGHBYTE = SECOND CHARACTER (200 BIT IS STRING FLAG).
; LENGTH OF ARRAY IN CORE IN BYTES (INCLUDES EVERYTHING).
; NUMBER OF DIMENSIONS.
; FOR EACH DIMENSION STARTING WITH THE FIRST A LIST
; (2 BYTES EACH) OF THE MAX INDICE+1
; THE VALUES
;
ISARY:
    lda DIMFLG
.if (INTPRC) <> 0
    ora INTFLG
.endif
;SAVE [DIMFLG] FOR RECURSION.
    pha
    lda VALTYP
;SAVE [VALTYP] FOR RECURSION.
    pha
;SET NUMBER OF DIMENSIONS TO ZERO.
    ldy #.lobyte(0)
;SAVE NUMBER OF DIMS.
INDLOP:
    tya
    pha
;SAVE LOOKS.
    PSHWD VARNAM
;EVALUATE INDICE INTO FACMO&LO.
    jsr INTIDX
;GET BACK ALL... WE'RE HOME.
    PULWD VARNAM
;(# OF DIMS).
    pla
    tay
    tsx
    lda 258,X
;PUSH DIMFLG AND VALTYP FURTHER.
    pha
    lda 257,X
    pha
;PUT INDICE ONTO STACK.
    lda INDICE
;UNDER DIMFLG AND VALTYP.
    sta 258,X
    lda INDICE+1
    sta 257,X
;INCREMENT # OF DIMS.
    iny
;GET TERMINATING CHARACTER.
    jsr CHRGOT
;A COMMA?
    cmp #.lobyte(44)
;YES.
    beq INDLOP
;SAVE COUNT OF DIMS.
    sty COUNT
;MUST BE CLOSED PAREN.
    jsr CHKCLS
    pla
;GET VALTYP AND
    sta VALTYP
    pla
.if (INTPRC) <> 0
    sta INTFLG
    and #.lobyte(127)
.endif
;DIMFLG OFF STACK.
    sta DIMFLG
;PLACE TO START SEARCH.
    ldx ARYTAB
    lda ARYTAB+1
LOPFDA:
    stx LOWTR
    sta LOWTR+1
;END OF ARRAYS?
    cmp STREND+1
    bne LOPFDV
    cpx STREND
;A FINE THING! NO ARRAY!.
    beq NOTFDD
LOPFDV:
    ldy #.lobyte(0)
    lda (LOWTR),y
    iny
;COMPARE HIGH ORDERS.
    cmp VARNAM
;NO WAY IS IT THIS. GET OUT OF HERE.
    bne NMARY1
    lda VARNAM+1
;LOW ORDERS?
    cmp (LOWTR),y
;WELL, HERE IT IS !!
    beq GOTARY
NMARY1:
    iny
;GET LENGTH.
    lda (LOWTR),y
    clc
    adc LOWTR
    tax
    iny
    lda (LOWTR),y
    adc LOWTR+1
;ALWAYS BRANCHES.
    bcc LOPFDA
;GET BAD SUB ERROR NUMBER.
BSERR:
    ldx #.lobyte(ERRBS)
    SKIP2
;TOO BIG. "FUNCTION CALL" ERROR.
FCERR:
    ldx #.lobyte(ERRFC)
ERRGO3:
    jmp ERROR
;PERHAPS A "RE-DIMENSION" ERROR
GOTARY:
    ldx #.lobyte(ERRDD)
;TEST THE DIMFLG
    lda DIMFLG
    bne ERRGO3
    jsr FMAPTR
;GET NUMBER OF DIMS INPUT.
    lda COUNT
    ldy #.lobyte(4)
;# OF DIMS THE SAME?
    cmp (LOWTR),y
;SAME SO GO GET DEFINITION.
    bne BSERR
    jmp GETDEF

;
; HERE WHEN VARIABLE IS NOT FOUND IN THE ARRAY TABLE.
;
; BUILDING AN ENTRY.
;
;	PUT DOWN THE DESCRIPTOR.
;	SETUP NUMBER OF DIMENSIONS.
;	MAKE SURE THERE IS ROOM FOR THE NEW ENTRY.
;	REMEMBER "VARPNT".
;	TALLY=4.
;	SKIP 2 LOCS FOR LATER FILL IN OF SIZE.
; LOOP: GET AN INDICE
;	PUT DOWN NUMBER+1 AND INCREMENT VARPTR.
;	TALLY=TALLY*NUMBER+1.
;	DECREMENT NUMBER-DIMS.
;	BNE LOOP
;	CALL "REASON" WITH [Y,A] REFLECTING LAST LOC OF VARIABLE.
;	UPDATE STREND.
;	ZERO ALL.
;	MAKE TALLY INCLUDE MAXDIMS AND DESCRIPTOR.
;	PUT DOWN TALLY.
;	IF CALLED BY DIMENSION, RETURN.
;	OTHERWISE INDEX INTO THE VARIABLE AS IF IT
;	 WERE FOUND ON THE INITIAL SEARCH.
;
;FORM ARYPNT.
NOTFDD:
    jsr FMAPTR
    jsr REASON
    lda #.lobyte(0)
    tay
    sta CURTOL+1
.if (ADDPRC) = 0
    ldx #.lobyte(4)
.endif
.if (ADDPRC) <> 0
    ldx #.lobyte(5)
.endif
;THIS CODE ONLY WORKS FOR INTPRC=1
    lda VARNAM
;IF ADDPRC=1.
    sta (LOWTR),y
.if (ADDPRC) <> 0
    bpl NOTFLT
    dex
.endif
NOTFLT:
    iny
    lda VARNAM+1
    sta (LOWTR),y
    bpl STOMLT
    dex
.if (ADDPRC) <> 0
    dex
.endif
STOMLT:
    stx CURTOL
    lda COUNT
.repeat 3
    iny
.endrepeat
;SAVE NUMBER OF DIMENSIONS.
    sta (LOWTR),y
;DEFAULT SIZE.
LOPPTA:
    ldx #.lobyte(11)
    lda #.lobyte(0)
    bit DIMFLG
;NOT IN A DIM STATEMENT.
    bvc NOTDIM
;GET LOW ORDER OF INDICE.
    pla
    clc
    adc #.lobyte(1)
    tax
;GET HIGH PART OF INDICE.
    pla
    adc #.lobyte(0)
NOTDIM:
    iny
;STORE HIGH PART OF INDICE.
    sta (LOWTR),y
    iny
    txa
;STORE LOW ORDER OF INDICE.
    sta (LOWTR),y
;[X,A]=[CURTOL]*[LOWTR,Y]
    jsr UMULT
;SAVE NEW TALLY.
    stx CURTOL
    sta CURTOL+1
    ldy INDEX
;ANY MORE INDICES LEFT?
    dec COUNT
;YES.
    bne LOPPTA
    adc ARYPNT+1
;OVERFLOW.
    bcs OMERR1
;COMPUTE WHERE TO ZERO.
    sta ARYPNT+1
    tay
    txa
    adc ARYPNT
    bcc GREASE
    iny
    beq OMERR1
;GET ROOM.
GREASE:
    jsr REASON
;NEW END OF STORAGE.
    STWD STREND
;STORING [ACCA] IS FASTER THAN CLEAR.
    lda #.lobyte(0)
    inc CURTOL+1
    ldy CURTOL
    beq DECCUR
ZERITA:
    dey
    sta (ARYPNT),y
;NO. CONTINUE.
    bne ZERITA
DECCUR:
    dec ARYPNT+1
    dec CURTOL+1
;DO ANOTHER BLOCK.
    bne ZERITA
;BUMP BACK UP. WILL USE LATER.
    inc ARYPNT+1
    sec
;RESTORE [ACCA].
    lda STREND
;DETERMINE LENGTH.
    sbc LOWTR
    ldy #.lobyte(2)
;LOW.
    sta (LOWTR),y
    lda STREND+1
    iny
    sbc LOWTR+1
;HIGH.
    sta (LOWTR),y
    lda DIMFLG
;BYE.
    bne DIMRTS
    iny
;
; AT THIS POINT [LOWTR,Y] POINTS BEYOND THE SIZE TO THE NUMBER OF
; DIMENSIONS. STRATEGY:
;	NUMDIM=NUMBER OF DIMENSIONS.
;	CURTOL=0.
; INLPNM:GET A NEW INDICE.
;	MAKE SURE INDICE IS NOT TOO BIG.
;	MULTIPLY CURTOL BY CURMAX.
;	ADD INDICE TO CURTOL.
;	NUMDIM=NUMDIM-1.
;	BNE	INLPNM.
;	USE [CURTOL]*4 AS OFFSET.
;
GETDEF:
    lda (LOWTR),y
;SAVE A COUNTER.
    sta COUNT
;ZERO [CURTOL].
    lda #.lobyte(0)
    sta CURTOL
INLPNM:
    sta CURTOL+1
    iny
;GET LOW INDICE.
    pla
    tax
    sta INDICE
;AND THE HIGH PART
    pla
    sta INDICE+1
;COMPARE WITH MAX INDICE.
    cmp (LOWTR),y
    bcc INLPN2
;IF GREATER, "BAD SUBSCRIPT" ERROR.
    bne BSERR7
    iny
    txa
    cmp (LOWTR),y
    bcc INLPN1
BSERR7:
    jmp BSERR
OMERR1:
    jmp OMERR
INLPN2:
    iny
;DON'T MULTIPLY IF CURTOL=0.
INLPN1:
    lda CURTOL+1
    ora CURTOL
;PREPARE TO GET INDICE BACK.
    clc
;GET HIGH PART OF INDICE BACK.
    beq ADDIND
;MULTIPLY [CURTOL] BY [LOWTR,Y,Y+1].
    jsr UMULT
    txa
;ADD IN [INDICE].
    adc INDICE
    tax
    tya
    ldy INDEX1
ADDIND:
    adc INDICE+1
    stx CURTOL
;ANY MORE?
    dec COUNT
;YES.
    bne INLPNM
;FIX ARRAY BUG ****
    sta CURTOL+1
.if (ADDPRC) = 0
    ldx #.lobyte(4)
.endif
.if (ADDPRC) <> 0
;THIS CODE ONLY WORKS FOR INTPRC=1
    ldx #.lobyte(5)
;IF ADDPRC=1.
    lda VARNAM
    bpl NOTFL1
    dex
.endif
NOTFL1:
    lda VARNAM+1
    bpl STOML1
    dex
.if (ADDPRC) <> 0
    dex
.endif
STOML1:
    stx ADDEND
    lda #.lobyte(0)
;ON RTS, A&Y=HI . X=LO.
    jsr UMULTD
    txa
    adc ARYPNT
    sta VARPNT
    tya
    adc ARYPNT+1
    sta VARPNT+1
    tay
    lda VARPNT
;RETURN TO CALLER.
DIMRTS:
    rts
; INTEGER ARITHMETIC ROUTINES.
;TWO BYTE UNSIGNED INTEGER MULTIPLY.
;THIS IS FOR MULTIPLY DIMENSIONED ARRAYS.
; [X,Y]=[X,A]=[CURTOL]*[LOWTR,Y,Y+1].
UMULT:
    sty INDEX
    lda (LOWTR),y
;LOW, THEN HIGH.
    sta ADDEND
    dey
;PUT [LOWTR,Y,Y+1] IN FASTER MEMORY.
    lda (LOWTR),y
UMULTD:
    sta ADDEND+1
    lda #.lobyte(16)
    sta DECCNT
;CLR THE ACCS.
    ldx #.lobyte(0)
;RESULT INITIALLY ZERO.
    ldy #.lobyte(0)
UMULTC:
    txa
;MULTIPLY BY TWO.
    asl A
    tax
    tya
    rol A
    tay
;TWO MUCH !
    bcs OMERR1
    asl CURTOL
    rol CURTOL+1
;NOTHING IN THIS POSITION TO MULTIPLY.
    bcc UMLCNT
    clc
    txa
    adc ADDEND
    tax
    tya
    adc ADDEND+1
    tay
;MAN, JUST TOO MUCH !
    bcs OMERR1
;DONE?
UMLCNT:
    dec DECCNT
;KEEP IT UP.
    bne UMULTC
;YES, ALL DONE.
UMLRTS:
    rts
; FRE FUNCTION AND INTEGER TO FLOATING ROUTINES.
FRE:
    lda VALTYP
    beq NOFREF
    jsr FREFAC
NOFREF:
    jsr GARBA2
    sec
;WE WANT
    lda FRETOP
;[FRETOP]-[STREND].
    sbc STREND
    tay
    lda FRETOP+1
    sbc STREND+1

GIVAYF:
    ldx #.lobyte(0)
    stx VALTYP
    STWD FACHO
;SET EXPONENT TO 2^16.
    ldx #.lobyte(144)
;TURN IT TO A FLOATING PNT #.
    jmp FLOATS

;GET POSITION.
POS:
    ldy TRMPOS
SNGFLT:
    lda #.lobyte(0)
;FLOAT IT.
    BEQA GIVAYF
; SIMPLE-USER-DEFINED-FUNCTION CODE.
;
; NOTE ONLY SINGLE ARGUMENTS ARE ALLOWED TO FUNCTIONS
; AND FUNCTIONS MUST BE OF THE SINGLE LINE FORM:
;	DEF FNA(X)=X^2+X-2
; NO STRINGS CAN BE INVOLVED WITH THESE FUNCTIONS.
;
; IDEA: CREATE A SIMPLE VARIABLE ENTRY
; WHOSE FIRST CHARACTER HAS THE 200 BIT SET.
; THE VALUE WILL BE:
;
;	A TEXT PNTR TO THE FORMULA.
;	A PNTR TO THE ARGUMENT VARIABLE.
;
; FUNCTION NAMES CAN BE LIKE "FNA4".
;
;
; SUBROUTINE TO SEE IF WE ARE IN DIRECT MODE.
; AND COMPLAIN IF SO.
;
;DIR MODE HAS [CURLIN]=0,255
ERRDIR:
    ldx CURLIN+1
;SO NOW, IS RESULT ZERO?
    inx
;YES.
    bne DIMRTS
;INPUT DIRECT ERROR CODE.
    ldx #.lobyte(ERRID)
    SKIP2
;USER DEFINED FUNCTION NEVER DEFINED
ERRGUF:
    ldx #.lobyte(ERRUF)
ERRGO1:
    jmp ERROR

;GET A PNTR TO THE FUNCTION.
DEF:
    jsr GETFNM
    jsr ERRDIR
;MUST HAVE "(".
    jsr CHKOPN
    lda #.lobyte(128)
;PROHIBIT SUBSCRIPTED VARIABLES.
    sta SUBFLG
;GET PNTR TO ARGUMENT.
    jsr PTRGET
;IS IT A NUMBER?
    jsr CHKNUM
;MUST HAVE ")"
    jsr CHKCLS
;MUST HAVE "=".
    SYNCHK EQULTK
;PUT CRAZY BYTE ON.
.if (ADDPRC) <> 0
    pha
.endif
    PSHWD VARPNT
    PSHWD TXTPTR
    jsr DATA
    jmp DEFFIN
;
; SUBROUTINE TO GET A PNTR TO A FUNCTION NAME.
;
;MUST START WITH FN.
GETFNM:
    SYNCHK FNTK
;PUT FUNCTION BIT ON.
    ora #.lobyte(128)
    sta SUBFLG
;GET POINTER TO FUNCTION OR CREATE ANEW.
    jsr PTRGT2
    STWD DEFPNT
;MAKE SURE IT'S NOT A STRING AND RETURN.
    jmp CHKNUM

;GET THE FUNCTION'S NAME.
FNDOER:
    jsr GETFNM
    PSHWD DEFPNT
;EVALUATE PARAMETER.
    jsr PARCHK
    jsr CHKNUM
    PULWD DEFPNT
    ldy #.lobyte(2)
;GET POINTER TO VARIABLE.
    lda (DEFPNT),y
;SAVE VARIABLE POINTER.
    sta VARPNT
    tax
    iny
    lda (DEFPNT),y
    beq ERRGUF
    sta VARPNT+1
;SINCE DEF USES ONLY 4.
.if (ADDPRC) <> 0
    iny
.endif
DEFSTF:
    lda (VARPNT),y
;PUSH IT ALL ON STACK.
    pha
;SINCE WE ARE RECURSING MAYBE.
    dey
    bpl DEFSTF
    ldy VARPNT+1
;PUT CURRENT FAC INTO OUR ARG VARIABLE.
    jsr MOVMF
;SAVE TEXT POINTER.
    PSHWD TXTPTR
;PNTR TO FUNCTION.
    lda (DEFPNT),y
    sta TXTPTR
    iny
    lda (DEFPNT),y
    sta TXTPTR+1
;SAVE VARIABLE POINTER.
    PSHWD VARPNT
;EVALUATE FORMULA AND CHECK NUMERIC.
    jsr FRMNUM
    PULWD DEFPNT
    jsr CHRGOT
;IT DIDN'T TERMINATE. HUH?
    JNE SNERR
;RESTORE TEXT PNTR.
    PULWD TXTPTR
DEFFIN:
    ldy #.lobyte(0)
;GET OLD ARG VALUE OFF STACK
    pla
;AND PUT IT BACK IN VARIABLE.
    sta (DEFPNT),y
    pla
    iny
    sta (DEFPNT),y
    pla
    iny
    sta (DEFPNT),y
    pla
    iny
    sta (DEFPNT),y
.if (ADDPRC) <> 0
    pla
    iny
    sta (DEFPNT),y
.endif
DEFRTS:
    rts
; STRING FUNCTIONS.
;
; THE STR$ FUNCTION TAKES A NUMBER AND GIVES A STRING
; WITH THE CHARACTERS THE OUTPUT OF THE NUMBER
; WOULD HAVE GIVEN.
;
;ARG HAS TO BE NUMERIC.
STR:
    jsr CHKNUM
    ldy #.lobyte(0)
;DO ITS OUTPUT.
    jsr FOUTC
    pla
    pla
TIMSTR:
    LDWDI LOFBUF
;SCAN IT AND TURN IT INTO A STRING.
    BEQA STRLIT
;
; "STRINI" GET STRING SPACE FOR THE CREATION OF A STRING AND
; CREATES A DESCRIPTOR FOR IT IN "DSCTMP".
;
;GET FACMO TO STORE IN DSCPNT.
STRINI:
    LDXY FACMO
;RETAIN THE DESCRIPTOR POINTER.
    STXY DSCPNT
;GET STRING SPACE.
STRSPA:
    jsr GETSPA
;SAVE LOCATION.
    STXY DSCTMP+1
;SAVE LENGTH.
    sta DSCTMP
;ALL DONE.
    rts
;
; "STRLT2" TAKES THE STRING LITERAL WHOSE FIRST CHARACTER
; IS POINTED TO BY [Y,A] AND BUILDS A DESCRIPTOR FOR IT.
; THE DESCRIPTOR IS INITIALLY BUILT IN "DSCTMP", BUT "PUTNEW"
; TRANSFERS IT INTO A TEMPORARY AND LEAVES A POINTER
; AT THE TEMPORARY IN FACMO&LO. THE CHARACTERS OTHER THAN
; ZERO THAT TERMINATE THE STRING SHOULD BE SET UP IN "CHARAC"
; AND "ENDCHR". IF THE TERMINATOR IS A QUOTE, THE QUOTE IS SKIPPED
; OVER. LEADING QUOTES SHOULD BE SKIPPED BEFORE JSR. ON RETURN
; THE CHARACTER AFTER THE STRING LITERAL IS POINTED TO
; BY [STRNG2].
;
;ASSUME STRING ENDS ON QUOTE.
STRLIT:
    ldx #.lobyte(34)
    stx CHARAC
    stx ENDCHR
;SAVE POINTER TO STRING.
STRLT2:
    STWD STRNG1
;IN CASE NO STRCPY.
    STWD DSCTMP+1
;INITIALIZE CHARACTER COUNT.
    ldy #.lobyte(255)
STRGET:
    iny
;GET CHARACTER.
    lda (STRNG1),y
;IF ZERO.
    beq STRFI1
;THIS TERMINATOR?
    cmp CHARAC
;YES.
    beq STRFIN
    cmp ENDCHR
;LOOK FURTHER.
    bne STRGET
;QUOTE?
STRFIN:
    cmp #.lobyte(34)
    beq STRFI2
;NO, BACK UP.
STRFI1:
    clc
;RETAIN COUNT.
STRFI2:
    sty DSCTMP
    tya
;WISHING TO SET [TXTPTR].
    adc STRNG1
    sta STRNG2
    ldx STRNG1+1
    bcc STRST2
    inx
STRST2:
    stx STRNG2+1
;IF PAGE 0, COPY SINCE IT IS EITHER
    lda STRNG1+1
;A STRING CONSTANT IN BUF OR A STR$
;RESULT IN LOFBUF
.if (BUFPAG) <> 0
    beq STRCP
    cmp #.lobyte(BUFPAG)
.endif
    bne PUTNEW
STRCP:
    tya
    jsr STRINI
    LDXY STRNG1
;MOVE STRING.
    jsr MOVSTR
;
; SOME STRING FUNCTION IS RETURNING A RESULT IN DSCTMP.
; SETUP A TEMP DESCRIPTOR WITH DSCTMP IN IT.
; PUT A POINTER TO THE DESCRIPTOR IN FACMO&LO AND FLAG THE
; RESULT AS TYPE STRING.
;
;POINTER TO FIRST FREE TEMP.
PUTNEW:
    ldx TEMPPT
    cpx #.lobyte(TEMPST+STRSIZ*NUMTMP)
    bne PUTNW1
;STRING TEMPORARY ERROR.
    ldx #.lobyte(ERRST)
;GO TELL HIM.
ERRGO2:
    jmp ERROR
PUTNW1:
    lda DSCTMP
    sta 0,X
    lda DSCTMP+1
    sta 1,X
    lda DSCTMP+2
    sta 2,X
    ldy #.lobyte(0)
    STXY FACMO
    sty FACOV
    dey
;TYPE IS "STRING".
    sty VALTYP
;SET POINTER TO LAST-USED TEMP.
    stx LASTPT
    inx
    inx
;POINT FURTHER.
    inx
;SAVE POINTER TO NEXT TEMP IF ANY.
    stx TEMPPT
;ALL DONE.
    rts

;
; GETSPA - GET SPACE FOR CHARACTER STRING.
; MAY FORCE GARBAGE COLLECTION.
;
; # OF CHARACTERS (BYTES) IN ACCA.
; RETURNS WITH POINTER IN [Y,X]. OTHERWISE (IF CAN'T GET
; SPACE) BLOWS OFF TO "OUT OF STRING SPACE" TYPE ERROR.
; ALSO PRESERVES [ACCA] AND SETS [FRESPC]=[Y,X]=PNTR AT SPACE.
;
;SIGNAL NO GARBAGE COLLECTION YET.
GETSPA:
    lsr GARBFL
;SAVE FOR LATER.
TRYAG2:
    pha
    eor #.lobyte(255)
;ADD ONE TO COMPLETE NEGATION.
    sec
    adc FRETOP
    ldy FRETOP+1
    bcs TRYAG3
    dey
;COMPARE HIGH ORDERS.
TRYAG3:
    cpy STREND+1
;MAKE ROOM FOR MORE.
    bcc GARBAG
;SAVE NEW FRETOP.
    bne STRFRE
;COMPARE LOW ORDERS.
    cmp STREND
;CLEAN UP.
    bcc GARBAG
;SAVE NEW [FRETOP].
STRFRE:
    STWD FRETOP
;PUT IT THERE OLD MAN.
    STWD FRESPC
;PRESERVE A IN X.
    tax
;GET COUNT BACK IN ACCA.
    pla
;ALL DONE.
    rts
;"OUT OF STRING SPACE"
GARBAG:
    ldx #.lobyte(ERROM)
    lda GARBFL
    bmi ERRGO2
    jsr GARBA2
    lda #.lobyte(128)
    sta GARBFL
;GET BACK STRING LENGTH.
    pla
;ALWAYS BRANCHES.
    bne TRYAG2
;START FROM TOP DOWN.
GARBA2:
.if (REALIO|DISKO) = 0
;TYPE "BELL".
    lda #.lobyte(7)
    jsr OUTDO
.endif
    ldx MEMSIZ
    lda MEMSIZ+1
;LIKE SO.
FNDVAR:
    stx FRETOP
    sta FRETOP+1
    ldy #.lobyte(0)
    sty GRBPNT+1
;BOTH BYTES SET TO ZERO (FIX BUG)
    sty GRBPNT
    LDWX STREND
    STWX GRBTOP
    LDWXI TEMPST
    STWX INDEX1
;DONE WITH TEMPS?
TVAR:
    cmp TEMPPT
;YEP.
    beq SVARS
    jsr DVAR
;LOOP.
    beq TVAR
SVARS:
    lda #.lobyte(6+ADDPRC)
    sta FOUR6
;GET START OF SIMPLE VARIABLES.
    LDWX VARTAB
    STWX INDEX1
;DONE WITH SIMPLE VARIABLES?
SVAR:
    cpx ARYTAB+1
;NO.
    bne SVARGO
    cmp ARYTAB
;YEP.
    beq ARYVAR
;DO IT , AGAIN.
SVARGO:
    jsr DVARS
;LOOP.
    beq SVAR
;SAVE FOR ADDITION.
ARYVAR:
    STWX ARYPNT
    lda #.lobyte(STRSIZ)
    sta FOUR6
;GET THE POINTER TO VARIABLE.
ARYVA2:
    LDWX ARYPNT
;DONE WITH ARRAYS?
ARYVA3:
    cpx STREND+1
;NO.
    bne ARYVGO
    cmp STREND
;YES, GO FINISH UP.
    JEQ GRBPAS
ARYVGO:
    STWX INDEX1
    ldy #.lobyte(1-ADDPRC)
.if (ADDPRC) <> 0
    lda (INDEX1),y
    tax
    iny
.endif
    lda (INDEX1),y
    php
    iny
    lda (INDEX1),y
    adc ARYPNT
;FORM POINTER TO NEXT ARRAY VAR.
    sta ARYPNT
    iny
    lda (INDEX1),y
    adc ARYPNT+1
    sta ARYPNT+1
    plp
    bpl ARYVA2
.if (ADDPRC) <> 0
    txa
    bmi ARYVA2
.endif
    iny
    lda (INDEX1),y
;RESET INDEX Y.
    ldy #.lobyte(0)
    asl A
;CARRY IS OFF AND OFF AFTER ADD.
    adc #.lobyte(5)
    adc INDEX1
    sta INDEX1
    bcc ARYGET
    inc INDEX1+1
ARYGET:
    ldx INDEX1+1
;END OF THE ARRAY?
ARYSTR:
    cpx ARYPNT+1
    bne GOGO
    cmp ARYPNT
;YES.
    beq ARYVA3
GOGO:
    jsr DVAR
;CYCLE.
    beq ARYSTR
DVARS:
.if (INTPRC) <> 0
    lda (INDEX1),y
    bmi DVARTS
.endif
    iny
    lda (INDEX1),y
    bpl DVARTS
    iny
;IS LENGTH=0?
DVAR:
    lda (INDEX1),y
;YES, RETURN.
    beq DVARTS
    iny
;GET LOW(ADR).
    lda (INDEX1),y
    tax
    iny
    lda (INDEX1),y
;COMPARE HIGHS.
    cmp FRETOP+1
;IF THIS STRING'S PNTR .GE. [FRETOP]
    bcc DVAR2
;NO NEED TO MESS WITH IT FURTHER.
    bne DVARTS
;COMPARE LOWS.
    cpx FRETOP
    bcs DVARTS
DVAR2:
    cmp GRBTOP+1
;IF THIS STRING IS BELOW PREVIOUS,
    bcc DVARTS
;FORGET IT.
    bne DVAR3
;COMPARE LOW ORDERS.
    cpx GRBTOP
;[X,A] .LE. [GRBTOP].
    bcc DVARTS
DVAR3:
    stx GRBTOP
    sta GRBTOP+1
    LDWX INDEX1
    STWX GRBPNT
    lda FOUR6
    sta SIZE
DVARTS:
    lda FOUR6
    clc
    adc INDEX1
    sta INDEX1
    bcc GRBRTS
    inc INDEX1+1
GRBRTS:
    ldx INDEX1+1
    ldy #.lobyte(0)
;DONE.
    rts
;
; HERE WHEN MADE ONE COMPLETE PASS THROUGH STRING VARIABLES.
;
;VARIABLE POINTER.
GRBPAS:
    lda GRBPNT+1
    ora GRBPNT
;ALL DONE.
    beq GRBRTS
    lda SIZE
;LEAVES C OFF.
    and #.lobyte(4)
    lsr A
    tay
    sta SIZE
    lda (GRBPNT),y
;NOTE: GRBTOP=LOWTR SO NO NEED TO SET LOWTR.
    adc LOWTR
    sta HIGHTR
    lda LOWTR+1
    adc #.lobyte(0)
    sta HIGHTR+1
    LDWX FRETOP
;WHERE IT ALL GOES.
    STWX HIGHDS
    jsr BLTUC
    ldy SIZE
    iny
;GET POSITION OF START OF RESULT.
    lda HIGHDS
    sta (GRBPNT),y
    tax
    inc HIGHDS+1
    lda HIGHDS+1
    iny
;CHANGE ADDR OF STRING IN VAR.
    sta (GRBPNT),y
;GO TO FNDVAR WITH SOMETHING FOR
    jmp FNDVAR
;[FRETOP].
;
; THE FOLLOWING ROUTINE CONCATENATES TWO STRINGS.
; THE FAC CONTAINS THE FIRST ONE AT THIS POINT.
; [TXTPTR] POINTS TO THE + SIGN.
;
;PSH HIGH ORDER ONTO STACK.
CAT:
    lda FACLO
    pha
;AND THE LOW.
    lda FACMO
    pha
;CAN COME BACK HERE SINCE
    jsr EVAL
;OPERATOR IS KNOWN.
;RESULT MUST BE STRING.
    jsr CHKSTR
    pla
;GET HIGH ORDER OF OLD DESC.
    sta STRNG1
    pla
    sta STRNG1+1
    ldy #.lobyte(0)
;GET LENGTH OF OLD STRING.
    lda (STRNG1),y
    clc
    adc (FACMO),y
;RESULT IS LESS THAN 256.
    bcc SIZEOK
;ERROR "LONG STRING".
    ldx #.lobyte(ERRLS)
    jmp ERROR
;INITIALIZE STRING.
SIZEOK:
    jsr STRINI
;MOVE IT.
    jsr MOVINS
;GET POINTER TO SECOND.
    LDWD DSCPNT
;FREE IT.
    jsr FRETMP
    jsr MOVDO
    LDWD STRNG1
    jsr FRETMP
    jsr PUTNEW
;"CAT" REENTERS FORM EVAL AT TSTOP.
    jmp TSTOP

;GET ADDR OF STRING.
MOVINS:
    ldy #.lobyte(0)
    lda (STRNG1),y
    pha
    iny
    lda (STRNG1),y
    tax
    iny
    lda (STRNG1),y
    tay
    pla
MOVSTR:
    STXY INDEX
MOVDO:
    tay
    beq MVDONE
    pha
MOVLP:
    dey
    lda (INDEX),y
    sta (FRESPC),y
QMOVE:
    tya
    bne MOVLP
    pla
MVDONE:
    clc
    adc FRESPC
    sta FRESPC
    bcc MVSTRT
    inc FRESPC+1
