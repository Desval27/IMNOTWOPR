    cmp #.lobyte(25)
    bcs SNERR3
    lda LINNUM
;MULTIPLY BY 10.
    asl A
    rol INDEX
    asl A
    rol INDEX
    adc LINNUM
    sta LINNUM
    lda INDEX
    adc LINNUM+1
    sta LINNUM+1
    asl LINNUM
    rol LINNUM+1
    lda LINNUM
;ADD IN DIGIT.
    adc CHARAC
    sta LINNUM
    bcc NXTLGC
    inc LINNUM+1
NXTLGC:
