    lda FACEXP
    cmp #.lobyte(8*ADDPRC+152)
;FORGET IT.
    bcs INTRTS
    jsr QINT
;CLR OVERFLOW BYTE.
    sty FACOV
    lda FACSGN
;MAKE FAC LOOK POSITIVE.
    sty FACSGN
;GET COMPLEMENT OF SIGN IN CARRY.
    eor #.lobyte(128)
    rol A
    lda #.lobyte(8*ADDPRC+152)
    sta FACEXP
    lda FACLO
    sta INTEGR
    jmp FADFLT
