; ARCTANGENT FUNCTION.
;USE IDENTITIES TO GET ARG BETWEEN 0 AND 1 AND THEN USE AN
;APPROXIMATION POLYNOMIAL TO COMPUTE ARCTAN(X).
;WHAT IS SIGN?
ATN:
    lda FACSGN
;(MEANWHILE SAVE FOR LATER.)
    pha
    bpl ATN1
;IF NEGATIVE, NEGATE FAC.
    jsr NEGOP
;USE ARCTAN(X)=-ARCTAN(-X) .
ATN1:
    lda FACEXP
;SAVE THIS TOO FOR LATER.
    pha
;SEE IF FAC .GE. 1.0 .
    cmp #.lobyte(129)
;IT IS LESS THAN 1.
    bcc ATN2
;GET PNTR TO 1.0 .
    LDWDI FONE
;COMPUTE RECIPROCAL.
    jsr FDIV
;USE ARCTAN(X)=PI/2-ARCTAN(1/X) .
;PNTR TO ARCTAN CONSTANTS.
ATN2:
    LDWDI ATNCON
    jsr POLYX
    pla
;WAS ORIGINAL ARGUMENT .LT. 1 ?
    cmp #.lobyte(129)
;YES.
    bcc ATN3
    LDWDI PI2
;SUBTRACT ARCTAGN FROM PI/2.
    jsr FSUB
;WAS ORIGINAL ARGUMENT POSITIVE?
ATN3:
    pla
;YES.
    bpl ATN4
;IF NEGATIVE, NEGATE RESULT.
    jmp NEGOP
;ALL DONE.
ATN4:
    rts

