    jsr TIMNUM
;WHOLE QTY BY 10.
    jsr MUL10
    inc FBUFPT
    ldy FBUFPT
    jsr TIMNUM
    jsr MOVAF
;IF NUM=0 THEN NO MULT.
    tax
;IF =0, GO TIT.
    beq NOML6
;MULT BY TWO.
    inx
    txa
;ADD IN AND MULT BY 2 GIVES *6.
    jsr FINML6
NOML6:
    ldy FBUFPT
    iny
;DONE ALL SIX?
    cpy #.lobyte(6)
    bne TIMELP
