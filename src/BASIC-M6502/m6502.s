; AND [A] = THE TERMINATING CHARACTER WITH CONDITION
; CODES SET UP TO REFLECT ITS VALUE.
;
LINGET:
    ldx #.lobyte(0)
;INITIALIZE LINE NUMBER TO ZERO.
    stx LINNUM
    stx LINNUM+1
;IT IS NOT A DIGIT.
MORLIN:
    bcs ONGRTS
;-1 SINCE C=0.
    sbc #.lobyte(48-1)
;SAVE CHARACTER.
    sta CHARAC
    lda LINNUM+1
    sta INDEX
