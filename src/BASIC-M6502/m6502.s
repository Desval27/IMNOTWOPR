    ldy #.lobyte(0)
;ZERO EXP AND HO (AND MOH).
    ldx #.lobyte(9+ADDPRC)
;ZERO MO AND LO.
FINZLP:
    sty DECCNT,X
;ZERO TENEXP AND EXPSGN
    dex
;ZERO DECCNT, DPTFLG.
    bpl FINZLP
;FLAGS STILL SET FROM CHRGET.
    bcc FINDGQ
;A NEGATIVE SIGN?
    cmp #.lobyte(45)
;NO, TRY PLUS SIGN.
    bne QPLUS
;IT'S NEGATIVE. (X=377).
    stx SGNFLG
;ALWAYS BRANCHES.
    beq FINC
;PLUS SIGN?
QPLUS:
    cmp #.lobyte(43)
;YES, SKIP IT.
    bne FIN1
FINC:
    jsr CHRGET
FINDGQ:
    bcc FINDIG
;THE DP?
FIN1:
    cmp #.lobyte(46)
;NO KIDDING.
    beq FINDP
;EXPONENT FOLLOWS.
    cmp #.lobyte(69)
;NO.
    bne FINE
;HERE TO CHECK FOR SIGN OF EXP.
;YES. GET ANOTHER.
    jsr CHRGET
;IT IS A DIGIT. (EASIER THAN
    bcc FNEDG1
;BACKING UP POINTER.)
;MINUS?
    cmp #.lobyte(MINUTK)
;NEGATE.
    beq FINEC1
;MINUS SIGN?
    cmp #.lobyte(45)
    beq FINEC1
;PLUS?
    cmp #.lobyte(PLUSTK)
    beq FINEC
;PLUS SIGN?
    cmp #.lobyte(43)
    beq FINEC
    bne FINEC2
;TURN IT ON.
FINEC1:
    BASIC_ROR {EXPSGN}
;GET ANOTHER.
FINEC:
    jsr CHRGET
;IT IS A DIGIT.
FNEDG1:
    bcc FINEDG
FINEC2:
    bit EXPSGN
    bpl FINE
    lda #.lobyte(0)
    sec
    sbc TENEXP
    jmp FINE1
FINDP:
    BASIC_ROR {DPTFLG}
    bit DPTFLG
    bvc FINC
FINE:
    lda TENEXP
FINE1:
    sec
;GET NUMBER OF PLACES TO SHIFT.
    sbc DECCNT
    sta TENEXP
;NEGATE?
    beq FINQNG
;POSITIVE SO MULTIPLY.
    bpl FINMUL
FINDIV:
    jsr DIV10
;DONE?
    inc TENEXP
;NO.
    bne FINDIV
;YES.
    beq FINQNG
FINMUL:
    jsr MUL10
;DONE?
    dec TENEXP
;NO
    bne FINMUL
FINQNG:
    lda SGNFLG
;IF POSITIVE, RETURN.
    bmi NEGXQS
    rts
;OTHERWISE, NEGATE AND RETURN.
NEGXQS:
    jmp NEGOP

FINDIG:
    pha
    bit DPTFLG
    bpl FINDG1
    inc DECCNT
FINDG1:
    jsr MUL10
;GET IT BACK.
    pla
    sec
    sbc #.lobyte(48)
;ADD IT IN.
    jsr FINLOG
    jmp FINC

FINLOG:
    pha
;SAVE FAC FOR LATER.
    jsr MOVAF
    pla
;FLOAT THE VALUE IN ACCA.
    jsr FLOAT
    lda ARGSGN
    eor FACSGN
;RESULTANT SIGN.
    sta ARISGN
;SET SIGNS ON THING TO ADD.
    ldx FACEXP
;ADD TOGETHER AND RETURN.
    jmp FADDT

;HERE PACK IN THE NEXT DIGIT OF THE EXPONENT.
;MULTIPLY THE OLD EXP BY 10 AND ADD IN THE NEXT
;DIGIT. NOTE: EXP OVERFLOW IS NOT CHECKED FOR.
;GET EXP SO FAR.
