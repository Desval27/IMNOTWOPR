CZLOOP:
    iny
    lda (INDEX),y
;NO, CONTINUE SEARCHING.
    bne CZLOOP
;GO ONE BEYOND.
    iny
    tya
    adc INDEX
    tax
    ldy #.lobyte(0)
    sta (INDEX),y
    lda INDEX+1
    adc #.lobyte(0)
    iny
    sta (INDEX),y
    stx INDEX
    sta INDEX+1
;ALWAYS BRANCHES.
    BCCA CHEAD
