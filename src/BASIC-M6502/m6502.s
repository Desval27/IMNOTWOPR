;A=0 IF ARG=FAC.
;A=-1 IF ARG .GT. FAC.
FCOMP:
    sta INDEX2
FCOMPN:
    sty INDEX2+1
    ldy #.lobyte(0)
;HAS ARGEXP.
    lda (INDEX2),y
;BUMP PNTR UP.
    iny
