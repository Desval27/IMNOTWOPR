    ldy #.lobyte(1)
    lda (LOWTR),y
    sta INDEX1+1
    lda VARTAB
    sta INDEX1
;SET TRANSFER TO.
    lda LOWTR+1
    sta INDEX2+1
    lda LOWTR
    dey
;COMPUTE NEGATIVE LENGTH.
    sbc (LOWTR),y
    clc
;COMPUTE NEW VARTAB.
    adc VARTAB
    sta VARTAB
;SET LOW OF TRANS TO.
    sta INDEX2
    lda VARTAB+1
    adc #.lobyte(255)
;COMPUTE HIGH OF VARTAB.
    sta VARTAB+1
;COMPUTE NUMBER OF BLOCKS TO MOVE.
    sbc LOWTR+1
    tax
    sec
    lda LOWTR
;COMPUTE OFFSET.
    sbc VARTAB
    tay
;IF VARTAB.LE.LOWTR,
    bcs QDECT1
;DECR DUE TO CARRY, AND
    inx
;DECREMENT STORE SO CARRY WORKS.
    dec INDEX2+1
QDECT1:
    clc
    adc INDEX1
    bcc MLOOP
    dec INDEX1+1
;FOR LATER ADCQ
    clc
MLOOP:
    lda (INDEX1),y
    sta (INDEX2),y
    iny
;BLOCK DONE?
    bne MLOOP
    inc INDEX1+1
    inc INDEX2+1
    dex
;DO ANOTHER BLOCK. ALWAYS.
    bne MLOOP
;RESET ALL VARIABLE INFO SO GARBAGE
NODEL:
    jsr RUNC
;COLLECTION CAUSED BY REASON WILL WORK
;FIX UP THE LINKS
    jsr LNKPRG
;SEE IF ANYTHNG THERE
    lda BUF
    beq MAIN
    clc
    lda VARTAB
;SETUP HIGHTR.
    sta HIGHTR
;ADD LENGTH OF LINE TO INSERT.
    adc COUNT
;THIS GIVES DEST ADDR.
    sta HIGHDS
    ldy VARTAB+1
;SAME FOR HIGH ORDERS.
    sty HIGHTR+1
    bcc NODELC
    iny
NODELC:
