    ldy #.lobyte(0)
    lda (DSCPNT),y
    sta (FORPNT),y
;POINT TO STRING PNTR.
    iny
    lda (DSCPNT),y
    sta (FORPNT),y
    iny
    lda (DSCPNT),y
    sta (FORPNT),y
    rts
