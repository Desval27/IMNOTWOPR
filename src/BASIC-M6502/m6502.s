;EXPONENTIATION ---  X^Y.
;N.B.  0^0=1
;FIRST CHECK IF Y=0. IF SO, THE RESULT IS 1.
;NEXT CHECK IF X=0. IF SO THE RESULT IS 0.
;THEN CHECK IF X.GT.0. IF NOT CHECK THAT Y IS AN INTEGER.
;IF SO, NEGATE X, SO THAT LOG DOESN'T GIVE FCERR.
;IF X IS NEGATIVE AND Y IS ODD, NEGATE THE RESULT
;RETURNED BY EXP.
;TO COMPUTE THE RESULT USE X^Y=EXP((Y*LOG(X)).
;IF FAC=0, JUST EXPONENTIATE THAT.
FPWRT:
    beq EXP
;IS X=0?
    lda ARGEXP
    bne FPWRT1
;ZERO FAC.
    jmp ZEROF1
;SAVE FOR LATER IN A TEMP.
FPWRT1:
    LDXYI TEMPF3
    jsr MOVMF
;Y=0 ALREADY. GOOD IN CASE NO ONE CALLS INT.
    lda ARGSGN
;NO PROBLEMS IF X.GT.0.
    bpl FPWR1
;INTEGERIZE THE FAC.
    jsr INT
;GET ADDR OF COMPERAND.
    LDWDI TEMPF3
;EQUAL?
    jsr FCOMP
;LEAVE X NEG. LOG WILL BLOW HIM OUT.
    bne FPWR1
;A=-1 AND Y IS IRRELEVANT.
;NEGATE X. MAKE POSITIVE.
    tya
