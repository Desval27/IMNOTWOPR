FOUTCP:
    cpx FACEXP
    bne FCOMPC
    lda (INDEX2),y
    ora #.lobyte(128)
    cmp FACHO
    bne FCOMPC
    iny
.if (ADDPRC) <> 0
    lda (INDEX2),y
    cmp FACMOH
    bne FCOMPC
    iny
.endif
    lda (INDEX2),y
    cmp FACMO
    bne FCOMPC
    iny
    lda #.lobyte(127)
    cmp FACOV
    lda (INDEX2),y
;GET ZERO IF EQUAL.
    sbc FACLO
    beq QINTRT
FCOMPC:
    lda FACSGN
    bcc FCOMPD
    eor #.lobyte(255)
;A PART OF SIGN SETS ACCA UP.
FCOMPD:
    jmp FCOMPS

; GREATEST INTEGER FUNCTION.
;QUICK GREATEST INTEGER FUNCTION.
;LEAVES INT(FAC) IN FACHO&MO&LO SIGNED.
;ASSUMES FAC .LT. 2^23 = 8388608
QINT:
    lda FACEXP
;IF ZERO, GOT IT.
    beq CLRFAC
    sec
;GET NUMBER OF PLACES TO SHIFT.
    sbc #.lobyte(8*ADDPRC+152)
    bit FACSGN
    bpl QISHFT
    tax
    lda #.lobyte(255)
;PUT 377 IN WHEN SHFTR SHIFTS BYTES.
    sta BITS
;TRULY NEGATE QUANTITY IN FAC.
    jsr NEGFCH
    txa
QISHFT:
    ldx #.lobyte(FAC)
    cmp #.lobyte(256-7)
;IF NUMBER OF PLACES .GE. 7
    bpl QINT1
;SHIFT 1 PLACE AT A TIME.
;START SHIFTING BYTES, THEN BITS.
    jsr SHIFTR
;ZERO BITS SINCE ADDER WANTS ZERO.
    sty BITS
QINTRT:
    rts
;PUT COUNT IN COUNTER.
QINT1:
    tay
    lda FACSGN
;GET SIGN BIT.
    and #.lobyte(128)
;SAVE FIRST SHIFTED BYTE.
    lsr FACHO
    ora FACHO
    sta FACHO
;SHIFT THE REST.
    jsr ROLSHF
;ZERO [BITS].
    sty BITS
    rts

