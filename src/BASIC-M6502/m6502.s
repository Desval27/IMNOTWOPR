; GENERAL STORAGE MANAGEMENT ROUTINES.
;
; FIND A "FOR" ENTRY ON THE STACK VIA "VARPNT".
;
FORSIZ = 2*ADDPRC+16
;LOAD XREG WITH STK PNTR.
FNDFOR:
    tsx
;IGNORE ADR(NEWSTT) AND RTS ADDR.
.repeat 4
    inx
.endrepeat
;GET STACK ENTRY.
FFLOOP:
    lda 257,X
;IS IT A "FOR" TOKEN?
    cmp #.lobyte(FORTK)
;NO, NO "FOR" LOOPS WITH THIS PNTR.
    bne FFRTS
;GET HIGH.
    lda FORPNT+1
    bne CMPFOR
;PNTR IS ZERO, SO ASSUME THIS ONE.
    lda 258,X
    sta FORPNT
    lda 259,X
    sta FORPNT+1
CMPFOR:
    cmp 259,X
;NOT THIS ONE.
    bne ADDFRS
;GET DOWN.
    lda FORPNT
    cmp 258,X
;WE GOT IT! WE GOT IT!
    beq FFRTS
ADDFRS:
    txa
;ADD 16 TO X.
    clc
    adc #.lobyte(FORSIZ)
;RESULT BACK INTO X.
    tax
    bne FFLOOP
;RETURN TO CALLER.
FFRTS:
    rts

;
; THIS IS THE BLOCK TRANSFER ROUTINE.
; IT MAKES SPACE BY SHOVING EVERYTHING FORWARD.
;
; ON ENTRY:
; [Y,A]=[HIGHDS]    (FOR REASON).
; [HIGHDS]= DESTINATION OF [HIGH ADDRESS].
; [LOWTR]= LOWEST ADDR TO BE TRANSFERRED.
; [HIGHTR]= HIGHEST ADDR TO BE TRANSFERRED.
;
; A CHECK IS MADE TO ASCERTAIN THAT A REASONABLE
; AMOUNT OF SPACE REMAINS BETWEEN THE BOTTOM
; OF THE STRINGS AND THE HIGHEST LOCATION TRANSFERRED INTO.
;
; ON EXIT:
; [LOWTR] ARE UNCHANGED.
; [HIGHTR]=[LOWTR]-200 OCTAL.
; [HIGHDS]=LOWEST ADDR TRANSFERRED INTO MINUS 200 OCTAL.
;
;ASCERTAIN THAT STRING SPACE WON'T
BLTU:
    jsr REASON
;BE OVERRUN.
    STWD STREND
;PREPARE TO SUBTRACT.
BLTUC:
    sec
    lda HIGHTR
;COMPUTE NUMBER OF THINGS TO MOVE.
    sbc LOWTR
;SAVE FOR LATER.
    sta INDEX
    tay
    lda HIGHTR+1
    sbc LOWTR+1
;PUT IT IN A COUNTER REGISTER.
    tax
;SO THAT COUNTER ALGORITHM WORKS.
    inx
;SEE IF LOW PART OF COUNT IS ZERO.
    tya
;YES, GO START MOVING BLOCKS.
    beq DECBLT
;NO, MUST MODIFY BASE ADDR.
    lda HIGHTR
    sec
;BORROW IS OFF SINCE [HIGHTR].GT.[LOWTR].
    sbc INDEX
;SAVE MODIFIED BASE ADDR.
    sta HIGHTR
;IF NO BORROW, GO SHOVE IT.
    bcs BLT1
;BORROW IMPLIES SUB 1 FROM HIGH ORDER.
    dec HIGHTR+1
    sec
;MOD BASE OF DEST ADDR.
BLT1:
    lda HIGHDS
    sbc INDEX
    sta HIGHDS
;NO BORROW.
    bcs MOREN1
;DECREMENT HIGH ORDER BYTE.
    dec HIGHDS+1
;ALWAYS SKIP.
    bcc MOREN1
;FETCH BYTE TO MOVE
BLTLP:
    lda (HIGHTR),y
;MOVE IT IN, MOVE IT OUT.
    sta (HIGHDS),y
MOREN1:
    dey
    bne BLTLP
;MOVE LAST OF THE BLOCK.
    lda (HIGHTR),y
    sta (HIGHDS),y
DECBLT:
    dec HIGHTR+1
;START ON NEW BLOCKS.
    dec HIGHDS+1
    dex
    bne MOREN1
;RETURN TO CALLER.
    rts

;
; THIS ROUTINE IS USED TO ASCERTAIN THAT A GIVEN
; NUMBER OF LOCS REMAIN AVAILABLE FOR THE STACK.
;    THE CALL IS:
;	LDAI	NUMBER OF 2-BYTE ENTRIES NEEDED.
;	JSR	GETSTK
;
; THIS ROUTINE MUST BE CALLED BY ANY ROUTINE WHICH PUTS
; AN ARBITRARY AMOUNT OF STUFF ON THE STACK,
; I.E., ANY RECURSIVE ROUTINE LIKE "FRMEVL".
; IT IS ALSO CALLED BY ROUTINES SUCH AS "GOSUB" AND "FOR"
; WHICH MAKE PERMANENT ENTRIES ON THE STACK.
;
; ROUTINES WHICH MERELY USE AND FREE UP THE GUARANTEED
; NUMLEV LOCATIONS NEED NOT CALL THIS.
;
;
; ON EXIT:
;    [A] AND [X] HAVE BEEN MODIFIED.
;
;MULT [A] BY 2. NB, CLEARS C BIT.
GETSTK:
    asl A
;MAKE SURE 2*NUMLEV+13 LOCS
    adc #.lobyte(2*NUMLEV+(3*ADDPRC)+13)
;(13 BECAUSE OF FBUFFR)
;WILL REMAIN IN STACK.
    bcs OMERR
    sta INDEX
;GET STACKED.
    tsx
;COMPARE.
    cpx INDEX
;IF STACK.LE.INDEX1, OM.
    bcc OMERR
    rts

;
; [Y,A] IS A CERTAIN ADDRESS. "REASON" MAKES SURE
; IT IS LESS THAN [FRETOP].
;
REASON:
    cpy FRETOP+1
    bcc REARTS
;GO GARB COLLECT.
    bne TRYMOR
    cmp FRETOP
    bcc REARTS
TRYMOR:
    pha
;IF TEMPF2 HAS ZERO IN BETWEEN.
    ldx #.lobyte(8+ADDPRC)
    tya
REASAV:
    pha
;SAVE HIGHDS ON STACK.
    lda HIGHDS-1,X
    dex
;PUT 8 OF THEM ON STK.
    bpl REASAV
;GO GARB COLLECT.
    jsr GARBA2
    ldx #.lobyte(256-8-ADDPRC)
REASTO:
    pla
;RESTORE AFTER GARB COLLECT.
    sta HIGHDS+8+ADDPRC,X
    inx
    bmi REASTO
    pla
    tay
;RESTORE A AND Y.
    pla
;COMPARE HIGHS
    cpy FRETOP+1
    bcc REARTS
;HIGHER IS BAD.
    bne OMERR
;AND THE LOWS.
    cmp FRETOP
    bcs OMERR
REARTS:
    rts

