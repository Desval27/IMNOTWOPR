    lda #.lobyte(0)
    sec
    sbc FACEXP
    sta FACEXP
;FIX UP EXPONENTS.
    jsr MULDIV
;SCALE IT RIGHT.
    inc FACEXP
;OVERFLOW.
    beq GOOVER
;SETUP PROCEDURE.
    ldx #.lobyte(256-3-ADDPRC)
    lda #.lobyte(1)
;THIS IS THE BEST CODE IN THE WHOLE PILE.
