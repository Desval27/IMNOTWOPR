    rts
;
; THIS IS THE LINE INPUT ROUTINE.
; IT READS CHARACTERS INTO BUF USING BACKARROW (UNDERSCORE, OR
; SHIFT O) AS THE DELETE CHARACTER AND @ AS THE 
; LINE DELETE CHARACTER. IF MORE THAN BUFLEN CHARACTERS
; ARE TYPED, NO ECHOING IS DONE UNTIL A BACKARROW OR @ OR CR
; IS TYPED. CONTROL-G WILL BE TYPED FOR EACH EXTRA CHARACTER.
; THE ROUTINE IS ENTERED AT INLIN.
;
.if (REALIO-4) = 0
;NO PROMPT CHARACTER
INLIN:
    ldx #.lobyte(128)
    stx CQPRMP
;GET A LINE ONTO PAGE 2
    jsr CQINLN
    cpx #.lobyte(BUFLEN-1)
;NOT TOO MANY CHARACTERS
    bcs GDBUFS
    ldx #.lobyte(BUFLEN-1)
;PUT A ZERO AT THE END
GDBUFS:
    lda #.lobyte(0)
    sta BUF,X
    txa
    beq NOCHR
LOPBHT:
    lda BUF-1,X
    and #.lobyte(127)
    sta BUF-1,X
    dex
    bne LOPBHT
NOCHR:
    lda #.lobyte(0)
;POINT AT THE BEGINNING
    LDXYI (BUF-1)
    rts
.endif
.if (REALIO <> 4) && (REALIO <> 6)
.if (REALIO-3) <> 0
LINLIN:
.if (REALIO-2) = 0
;ECHO IT.
    jsr OUTDO
.endif
;BACKARROW SO BACKUP PNTR AND
    dex
;GET ANOTHER IF COUNT IS POSITIVE.
    bpl INLINC
INLINN:
.if (REALIO-2) = 0
;PRINT THE @ OR A SECOND BACKARROW
    jsr OUTDO
.endif
;IF THERE WERE TOO MANY.
    jsr CRDO
.endif
INLIN:
    ldx #.lobyte(0)
;GET A CHARACTER.
INLINC:
    jsr INCHR
.if (REALIO-3) <> 0
;IS IT BOB ALBRECHT RINGING THE BELL
    cmp #.lobyte(7)
;FOR SCHOOL KIDS?
    beq GOODCH
.endif
;CARRIAGE RETURN?
    cmp #.lobyte(13)
;YES, FINISH UP.
    beq FININ1
.if (REALIO-3) <> 0
;CHECK FOR FUNNY CHARACTERS.
    cmp #.lobyte(32)
    bcc INLINC
;IS IT TILDA OR DELETE?
    cmp #.lobyte(125)
;BIG BAD ONES TOO.
    bcs INLINC
;LINE DELETE?
    cmp #.lobyte(64)
;YES.
    beq INLINN
;CHARACTER DELETE?
    cmp #.lobyte(95)
;YES.
    beq LINLIN
.endif
GOODCH:
.if (REALIO-3) <> 0
;LEAVE ROOM FOR NULL.
    cpx #.lobyte(BUFLEN-1)
;COMMO ASSURES US NEVER MORE THAN BUFLEN.
    bcs OUTBEL
.endif
    sta BUF,X
    inx
.if (REALIO-2) = 0
    SKIP2
.endif
.if (REALIO-2) <> 0
    bne INLINC
.endif
.if (REALIO-3) <> 0
OUTBEL:
    lda #.lobyte(7)
.if (REALIO) <> 0
;ECHO IT.
    jsr OUTDO
.endif
;CYCLE ALWAYS.
    bne INLINC
.endif
;GO TO FININL FAR, FAR AWAY.
FININ1:
    jmp FININL
.endif
INCHR:
.if REALIO = 6
    jsr WOPR_GETC
.endif
.if (REALIO-3) = 0
;FOR COMMODORE.
    jsr CQINCH
.endif
.if (REALIO-2) = 0
INCHRL:
    lda 64512
.repeat 4
    nop
.endrepeat
    lsr A
    bcc INCHRL
;GET THE CHARACTER.
    lda 64513
.repeat 4
    nop
.endrepeat
    and #.lobyte(127)
.endif
.if (REALIO-1) = 0
;1E5A FOR MOS TECH.
    jsr 7770
.endif
.if (REALIO-4) = 0
;FD0C FOR APPLE COMPUTER.
    jsr CQINCH
    and #.lobyte(127)
.endif
.if (REALIO) = 0
;GET A CHARACTER FROM SIMULATOR
    .error "PDP-10 simulator instruction is not supported"
.endif

.if (REALIO) <> 0
.if (EXTIO) <> 0
;CNT-O HAS NO EFFECT IF NOT FROM TERM.
    ldy CHANNL
    bne INCRTS
.endif
;SUPPRESS OUTPUT CHARACTER (^W).
    cmp #.lobyte(CONTW)
;NO, RETURN.
    bne INCRTS
    pha
;COMPLEMENT ITS STATE.
    COM CNTWFL
    pla
.endif
;END OF INCHR.
INCRTS:
    rts

;
; ALL "RESERVED" WORDS ARE TRANSLATED INTO SINGLE
; BYTES WITH THE MSB ON. THIS SAVES SPACE AND TIME 
; BY ALLOWING FOR TABLE DISPATCH DURING EXECUTION.
; THEREFORE ALL STATEMENTS APPEAR TOGETHER IN THE
; RESERVED WORD LIST IN THE SAME ORDER THEY
; APPEAR IN STMDSP.
;
;THE AMOUNT TO OFFSET THE LOW BYTE
BUFOFS .set 0
;OF THE TEXT POINTER TO GET TO BUF
;AFTER TXTPTR HAS BEEN SETUP TO POINT INTO BUF
.if (BUFPAG) <> 0
BUFOFS .set (BUF/256)*256
.endif
;SET SOURCE POINTER.
CRUNCH:
    ldx TXTPTR
;SET DESTINATION OFFSET.
    ldy #.lobyte(4)
;ALLOW CRUNCHING.
    sty DORES
KLOOP:
    lda BUFOFS,X
.if (REALIO-3) = 0
;GO LOOK AT SPACES.
    bpl CMPSPC
;PI??
    cmp #.lobyte(PI)
;GO SAVE IT.
    beq STUFFH
;SKIP NO PRINTING.
    inx
;ALWAYS GOES.
    bne KLOOP
.endif
;IS IT A SPACE TO SAVE?
CMPSPC:
    cmp #.lobyte(32)
;YES, GO SAVE IT.
    beq STUFFH
;IF IT'S A QUOTE, THIS WILL
    sta ENDCHR
;STOP LOOP WHEN OTHER QUOTE APPEARS.
;QUOTE SIGN?
    cmp #.lobyte(34)
;YES, DO SPECIAL STRING HANDLING.
    beq STRNG
;TEST FLAG.
    bit DORES
;NO CRUNCH, JUST STORE.
    bvs STUFFH
;A QMARK?
    cmp #.lobyte(63)
    bne KLOOP1
;YES, STUFF A "PRINT" TOKEN.
    lda #.lobyte(PRINTK)
;ALWAYS GO TO STUFFH.
    bne STUFFH
;SKIP NUMERICS.
KLOOP1:
    cmp #.lobyte(48)
    bcc MUSTCR
;":" AND ";" ARE ENTERED STRAIGHTAWAY.
    cmp #.lobyte(60)
    bcc STUFFH
;SAVE BUFFER POINTER.
MUSTCR:
    sty BUFPTR
;LOAD RESLST POINTER.
    ldy #.lobyte(0)
;ALSO CLEAR COUNT.
    sty COUNT
    dey
;SAVE TEXT POINTER FOR LATER USE.
    stx TXTPTR
    dex
RESER:
    iny
RESPUL:
    inx
RESCON:
    lda BUFOFS,X
;PREPARE TO SUBSTARCT.
    sec
;CHARACTERS EQUAL?
    sbc RESLST,Y
;YES, CONTINUE SEARCH.
    beq RESER
;NO BUT MAYBE THE END IS HERE.
    cmp #.lobyte(128)
;NO, TRULY UNEQUAL.
    bne NTHIS
    ora COUNT
;GET BUFFER PNTR.
GETBPT:
    ldy BUFPTR
STUFFH:
    inx
    iny
    sta BUF-5,Y
    lda BUF-5,Y
;NULL IMPLIES END OF LINE.
    beq CRDONE
;PREPARE TO SUBSTARCT.
    sec
;IS IT A ":"?
    sbc #.lobyte(58)
;YES, ALLOW CRUNCHING AGAIN.
    beq COLIS
;IS IT A DATATK?
    cmp #.lobyte(DATATK-58)
;NO, SEE IF IT IS REM TOKEN.
    bne NODATT
;SETUP FLAG.
COLIS:
    sta DORES
;PREP TO SBCQ
NODATT:
    sec
;REM ONLY STOPS ON NULL.
    sbc #.lobyte(REMTK-58)
;NO, CONTINUE CRUNCHING.
    bne KLOOP
;REM STOPS ONLY ON NULL, NOT : OR ".
    sta ENDCHR
STR1:
    lda BUFOFS,X
;YES, END OF LINE, SO DONE.
    beq STUFFH
;END OF GOBBLE?
    cmp ENDCHR
;YES, DONE WITH STRING.
    beq STUFFH
;INCREMENT BUFFER POINTER.
STRNG:
    iny
    sta BUF-5,Y
    inx
;PROCESS NEXT CHARACTER.
    bne STR1
;RESTORE TEXT POINTER.
NTHIS:
    ldx TXTPTR
;INCREMENT RES WORD COUNT.
    inc COUNT
NTHIS1:
    iny
;GET RES CHARACTER.
    lda RESLST-1,Y
;END OF ENTRY?
    bpl NTHIS1
;YES. IS IT THE END?
    lda RESLST,Y
;NO, TRY THE NEXT WORD.
    bne RESCON
;YES, END OF TABLE. GET 1ST CHR.
    lda BUFOFS,X
;STORE IT AWAY (ALWAYS BRANCHES).
    bpl GETBPT
;SO THAT IF THIS IS A DIR STATEMENT
CRDONE:
    sta BUF-3,Y
;ITS END WILL LOOK LIKE END OF PROGRAM.
.if (((BUF+BUFLEN)/256)-((BUF-1)/256)) <> 0
    dec TXTPTR+1
.endif
;MAKE TXTPTR POINT TO
    lda #.lobyte((BUF&255)-1)
;CRUNCHED LINE.
    sta TXTPTR
;RETURN TO CALLER.
LISTRT:
    rts
;
; FNDLIN SEARCHES THE PROGRAM TEXT FOR THE LINE
; WHOSE NUMBER IS PASSED IN "LINNUM".
; THERE ARE TWO POSSIBLE RETURNS:
;
;	1) CARRY SET.
;	   LOWTR POINTS TO THE LINK FIELD IN THE LINE
;	   WHICH IS THE ONE SEARCHED FOR.
;
;	2) CARRY NOT SET.
;	   LINE NOT FOUND. [LOWTR] POINTS TO THE LINE IN THE
;	   PROGRAM GREATER THAN THE ONE SOUGHT AFTER.
;
;LOAD [X,A] WITH [TXTTAB]
FNDLIN:
    LDWX TXTTAB
FNDLNC:
    ldy #.lobyte(1)
;STORE [X,A] INTO LOWTR
    STWX LOWTR
;SEE IF LINK IS 0
    lda (LOWTR),y
    beq FLINRT
    iny
    iny
;COMP HIGH ORDERS OF LINE NUMBERS.
    lda LINNUM+1
    cmp (LOWTR),y
;NO SUCH LINE NUMBER.
    bcc FLNRTS
    beq FNDLO1
    dey
;ALWAYS BRANCH.
    bne AFFRTS
FNDLO1:
    lda LINNUM
    dey
;COMPARE LOW ORDERS.
    cmp (LOWTR),y
;NO SUCH NUMBER.
    bcc FLNRTS
;GO TIT.
    beq FLNRTS
AFFRTS:
    dey
;FETCH LINK.
    lda (LOWTR),y
    tax
    dey
    lda (LOWTR),y
;ALWAYS BRANCHES.
    bcs FNDLNC
;C MAY BE HIGH.
FLINRT:
    clc
;RETURN TO CALLER.
FLNRTS:
    rts
;
; THE "NEW" COMMAND CLEARS THE PROGRAM TEXT AS WELL
; AS VARIABLE SPACE.
;
;MAKE SURE THERE IS A TERMINATOR.
SCRATH:
    bne FLNRTS
;GET A CLEARER.
SCRTCH:
    lda #.lobyte(0)
;SET UP INDEX.
    tay
;CLEAR	FIRST LINK.
    sta (TXTTAB),y
    iny
    sta (TXTTAB),y
    lda TXTTAB
    clc
    adc #.lobyte(2)
;SETUP [VARTAB].
    sta VARTAB
    lda TXTTAB+1
    adc #.lobyte(0)
    sta VARTAB+1
RUNC:
    jsr STXTPT
;SET ZERO FLAG
    lda #.lobyte(0)
;
; THIS CODE IS FOR THE CLEAR COMMAND.
;
;SYNTAX ERROR IF NO TERMINATOR.
CLEAR:
    bne STKRTS
;
; CLEAR INITIALIZES THE VARIABLE AND
; ARRAY SPACE BY RESETING ARYTAB (THE END OF SIMPLE VARIABLE SPACE)
; AND STREND (THE END OF ARRAY STORAGE). IT FALLS INTO "STKINI"
; WHICH RESETS THE STACK. 
;
;FREE UP STRING SPACE.
CLEARC:
    LDWD MEMSIZ
    STWD FRETOP
.if (EXTIO) <> 0
;CLOSE ALL OPEN FILES.
    jsr CQCALL
.endif
;LIBERATE THE
    LDWD VARTAB
;VARIABLES AND
    STWD ARYTAB
;ARRAYS.
    STWD STREND
;RESTORE DATA.
FLOAD:
    jsr RESTOR
;
; STKINI RESETS THE STACK POINTER ELIMINATING
; GOSUB AND FOR CONTEXT. STRING TEMPORARIES ARE FREED
; UP, SUBFLG IS RESET. CONTINUING IS PROHIBITED.
; AND A DUMMY ENTRY IS LEFT AT THE BOTTOM OF THE STACK SO "FNDFOR" WILL ALWAYS
; FIND A NON-"FOR" ENTRY AT THE BOTTOM OF THE STACK.
;
;INITIALIZE STRING TEMPORARIES.
STKINI:
    ldx #.lobyte(TEMPST)
    stx TEMPPT
;SETUP RETURN ADDRESS.
    pla
    tay
    pla
    ldx #.lobyte(STKEND-257)
    txs
    pha
    tya
    pha
    lda #.lobyte(0)
;DISALLOWING CONTINUING
    sta OLDTXT+1
;ALLOW SUBSCRIPTS.
    sta SUBFLG
STKRTS:
    rts

STXTPT:
    clc
    lda TXTTAB
    adc #.lobyte(255)
    sta TXTPTR
    lda TXTTAB+1
    adc #.lobyte(255)
;SETUP TEXT POINTER.
    sta TXTPTR+1
    rts
; THE "LIST" COMMAND.

;IT IS A DIGIT.
LIST:
    bcc GOLST
;IT IS A TERMINATOR.
    beq GOLST
;DASH PRECEDING?
    cmp #.lobyte(MINUTK)
;NO, SO SYNTAX ERROR.
    bne STKRTS
;GET LINE NUMBER INTO NUMLIN.
GOLST:
    jsr LINGET
;FIND LINE .GE. [NUMLIN].
    jsr FNDLIN
;GET LAST CHARACTER.
    jsr CHRGOT
;IF END OF LINE, # IS THE END.
    beq LSTEND
;DASH?
    cmp #.lobyte(MINUTK)
;IF NOT, SYNTAX ERROR.
    bne FLNRTS
;GET NEXT CHAR.
    jsr CHRGET
;GET END #.
    jsr LINGET
;IF NOT TERMINATOR, ERROR.
    bne FLNRTS
LSTEND:
    pla
;GET RID OF "NEWSTT" RTS ADDR.
    pla
;SEE IF IT WAS EXISTENT.
    lda LINNUM
    ora LINNUM+1
;IT WAS TYPED.
    bne LIST4
    lda #.lobyte(255)
    sta LINNUM
;MAKE IT HUGE.
    sta LINNUM+1
LIST4:
    ldy #.lobyte(1)
.if (REALIO-3) = 0
    sty DORES
.endif
;IS LINK ZERO?
    lda (LOWTR),y
;YES, GO TO READY.
    beq GRODY
.if (REALIO) <> 0
;LISTEN FOR CONT-C.
    jsr ISCNTC
.endif
;PRINT CRLF TO START WITH.
    jsr CRDO
    iny
    lda (LOWTR),y
    tax
    iny
;GET LINE NUMBER.
    lda (LOWTR),y
;SEE IF BEYOND LAST.
    cmp LINNUM+1
;GO DETERMINE RELATION.
    bne TSTDUN
;WAS EQUAL SO TEST LOW ORDER.
    cpx LINNUM
;EQUAL, SO LIST IT.
    beq TYPLIN
;IF LINE IS GR THAN LAST, THEN DUNE.
TSTDUN:
    bcs GRODY
TYPLIN:
    sty LSTPNT
;PRINT AS INT WITHOUT LEADING SPACE.
    jsr LINPRT
;ALWAYS PRINT SPACE AFTER NUMBER.
    lda #.lobyte(32)
;GET POINTER TO LINE BACK.
PRIT4:
    ldy LSTPNT
    and #.lobyte(127)
;PRINT CHAR.
PLOOP:
    jsr OUTDO
.if (REALIO-3) = 0
    cmp #.lobyte(34)
    bne PLOOP1
;IF QUOTE, COMPLEMENT FLAG.
    COM DORES
.endif
PLOOP1:
    iny
;IF WE HAVE PRINTED 256 CHARACTERS
    beq GRODY
;THE PROGRAM MUST BE MISFORMATED IN
;MEMORY DUE TO A BAD LOAD OR BAD
;HARDWARE. LET THE GUY RECOVER
;GET NEXT CHAR. IS IT ZERO?
    lda (LOWTR),y
;YES. END OF LINE.
    bne QPLOP
    tay
    lda (LOWTR),y
    tax
    iny
    lda (LOWTR),y
    stx LOWTR
    sta LOWTR+1
;BRANCH IF SOMETHING TO LIST.
    bne LIST4
GRODY:
    jmp READY
;IS IT A TOKEN?
;NO, HEAD FOR PRINTER.
QPLOP:
    bpl PLOOP
.if (REALIO-3) = 0
    cmp #.lobyte(PI)
    beq PLOOP
;INSIDE QUOTE MARKS?
    bit DORES
;YES, JUST TYPE THE CHARACTER.
    bmi PLOOP
.endif
    sec
;GET RID OF SIGN BIT AND ADD 1.
    sbc #.lobyte(127)
;MAKE IT A COUNTER.
    tax
;SAVE POINTER TO LINE.
    sty LSTPNT
;LOOK AT RES'D WORD LIST.
    ldy #.lobyte(255)
;IS THIS THE RES'D WORD?
RESRCH:
    dex
;YES, GO TOSS IT UP..
    beq PRIT3
RESCR1:
    iny
;END OF ENTRY?
    lda RESLST,Y
;NO, CONTINUE PASSING.
    bpl RESCR1
    bmi RESRCH
PRIT3:
    iny
    lda RESLST,Y
;END OF RESERVED WORD.
    bmi PRIT4
;PRINT IT.
    jsr OUTDO
;END OF ENTRY? NO, TYPE REST.
    bne PRIT3
; THE "FOR" STATEMENT.
;
; A "FOR" ENTRY ON THE STACK HAS THE FOLLOWING FORMAT:
;
; LOW ADDRESS
;	TOKEN (FORTK) 1 BYTE
;	A POINTER TO THE LOOP VARIABLE 2 BYTES
;	THE STEP 4+ADDPRC BYTES
;	A BYTE REFLECTING THE SIGN OF THE INCREMENT 1 BYTE
;	THE UPPER VALUE 4+ADDPRC BYTES
;	THE LINE NUMBER OF THE "FOR" STATEMENT 2 BYTES
;	A TEXT POINTER INTO THE "FOR" STATEMENT 2 BYTES
; HIGH ADDRESS
;
; TOTAL 16+2*ADDPRC BYTES.
;

;DON'T RECOGNIZE
FOR:
    lda #.lobyte(128)
;SUBSCRIPTED VARIABLES.
    sta SUBFLG
;READ THE VARIABLE AND ASSIGN IT
    jsr LET
;THE CORRECT INITIAL VALUE AND STORE
;A POINTER TO THE VARIABLE IN VARPNT.
;PNTR IS IN VARPNT, AND FORPNT.
    jsr FNDFOR
;IF NO MATCH, DON'T ELIMINATE ANYTHING.
    bne NOTOL
;MAKE IT ARITHMETICAL.
    txa
;ELIMINATE ALMOST ALL.
    adc #.lobyte(FORSIZ-3)
;NOTE C=1, THEN PLA, PLA.
    tax
;MANIFEST.
    txs
;GET RID OF NEWSTT RETURN ADDRESS
NOTOL:
    pla
;IN CASE THIS IS A TOTALLY NEW ENTRY.
    pla
    lda #.lobyte(8+ADDPRC)
;MAKE SURE 16 BYTES ARE AVAILABLE.
    jsr GETSTK
;GET A COUNT IN [Y] OF THE NUMBER OF
    jsr DATAN
;CHACRACTERS LEFT IN THE "FOR" STATEMENT
;[TXTPTR] IS UNAFFECTED.
;PREP TO ADD.
    clc
;SAVE IT FOR PUSHING.
    tya
    adc TXTPTR
    pha
    lda TXTPTR+1
    adc #.lobyte(0)
    pha
;PUT LINE NUMBER ON STACK.
    PSHWD CURLIN
;"TO" IS NECESSARY.
    SYNCHK TOTK
;VALUE MUST BE A NUMBER.
    jsr CHKNUM
;GET UPPER VALUE INTO FAC.
    jsr FRMNUM
;PACK FAC.
    lda FACSGN
    ora #.lobyte(127)
    and FACHO
;SET PACKED SIGN BIT.
    sta FACHO
    LDWDI LDFONE
    STWD INDEX1
;PUT FAC ONTO STACK, PACKED.
    jmp FORPSH
;PUT 1.0 INTO FAC.
LDFONE:
    LDWDI FONE
    jsr MOVFM
    jsr CHRGOT
;A STEP IS GIVEN?
    cmp #.lobyte(STEPTK)
;NO. ASSUME 1.0.
    bne ONEON
;YES. ADVANCE POINTER.
    jsr CHRGET
;READ THE STEP.
    jsr FRMNUM
;GET SIGN IN ACCA.
ONEON:
    jsr SIGN
;PUSH FAC ONTO STACK (THRU A).
    jsr PUSHF
;PUT PNTR TO VARIABLE ON STACK.
    PSHWD FORPNT
;PUT A FORTK ONTO STACK.
NXTCON:
    lda #.lobyte(FORTK)
    pha
;	BNEA	NEWSTT		;SIMULATE BNE TO NEWSTT. JUST FALL IN.
; NEW STATEMENT FETCHER.
;
; BACK HERE FOR NEW STATEMENT. CHARACTER POINTED TO BY TXTPTR
; IS ":" OR END-OF-LINE. THE ADDRESS OF THIS LOC IS LEFT
; ON THE STACK WHEN A STATEMENT IS EXECUTED SO THAT
; IT CAN MERELY DO A RTS WHEN IT IS DONE.
;
NEWSTT:
.if (REALIO) <> 0
;LISTEN FOR CONTROL-C.
    jsr ISCNTC
.endif
;LOOK AT CURRENT CHARACTER.
    LDWD TXTPTR
.if (BUFPAG) <> 0
;SEE IF IT WAS DIRECT BY CHECK FOR BUF'S PAGE NUMBER
    cpy #.lobyte(BUFPAG)
.endif
    beq DIRCON
;SAVE IN CASE OF RESTART BY INPUT.
    STWD OLDTXT
.if (BUFPAG) <> 0
DIRCON:
.endif
    ldy #.lobyte(0)
.if (BUFPAG) = 0
DIRCON:
.endif
    lda (TXTPTR),y
;NOT NULL -- CHECK WHAT IT IS
    bne MORSTS
;LOOK AT LINK.
    ldy #.lobyte(2)
;IS LINK 0?
    lda (TXTPTR),y
;CLEAR CARRY FOR ENDCON AND MATH THAT FOLLOWS
    clc
;YES - RAN OFF THE END.
    JEQ ENDCON
;PUT LINE NUMBER IN CURLIN.
    iny
    lda (TXTPTR),y
    sta CURLIN
    iny
    lda (TXTPTR),y
    sta CURLIN+1
    tya
    adc TXTPTR
    sta TXTPTR
    bcc GONE
    inc TXTPTR+1
;GET THE STATEMENT TYPE.
GONE:
    jsr CHRGET
    jsr GONE3
    jmp NEWSTT
;IF TERMINATOR, TRY AGAIN.
GONE3:
    beq ISCRTS
;NO NEED TO SET UP CARRY SINCE IT WILL
;BE ON IF NON-NUMERIC AND NUMERICS
;WILL CAUSE A SYNTAX ERROR LIKE THEY SHOULD
;" ON ... GOTO AND GOSUB" COME HERE.
GONE2:
    sbc #.lobyte(ENDTK)
    bcc GLET
    cmp #.lobyte(SCRATK-ENDTK+1)
;SOME RES'D WORD BUT NOT
    bcs SNERRX
;A STATEMENT RES'D WORD.
;MULTIPLY BY TWO.
    asl A
;MAKE AN INDEX.
    tay
    lda STMDSP+1,Y
    pha
    lda STMDSP,Y
;PUT DISP ADDR ONTO STACK.
    pha
    jmp CHRGET
;MUST BE A LET
GLET:
    jmp LET
MORSTS:
    cmp #.lobyte(58)
;IF A ":" CONTINUE STATEMENT
    beq GONE
;NEITHER 0 OR ":" SO SYNTAX ERROR
SNERR1:
    jmp SNERR
SNERRX:
    cmp #.lobyte(GOTK-ENDTK)
    bne SNERR1
